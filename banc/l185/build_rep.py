"""L185 builder: count-asserted ADDITIVE transform of the certified L175
harness banc/l175/scan_run.py -> banc/l185/rep_run.py. Run from banc/ (cwd
law). Every rep is count-pinned; long blocks are spliced on UNIQUE OPENERS.

What stays VERBATIM from l175/scan_run.py (itself a transform of
l150_run.py): extraction, ladder, build()/wb()/pools_for(), every lineage
arm's plumbing (incl. cutwA), add_arm()/gen_init(), the out-weight tables,
USED / POOL_A / POOL_C, settle_states body, bisect_vec, the rollout step
loop, store keys, per-seed atomic checkpoints.
What is REPLACED: seeds (fresh B40 + one L175 reproduction anchor), the
arm list block (R1/R2/R3 arms; add_alias/add_base_alias; R3 selection
mode), the gains + anchors block (stored gains reused EXACTLY, fixed-gain
and gain-grid arms, three in-run anchors), the tail. Census mode removed.
"""
import hashlib
import py_compile

SRC = "l175/scan_run.py"
s = open(SRC).read()
SRC_SHA = hashlib.sha256(s.encode()).hexdigest()
assert SRC_SHA == ("bbfea4e07ff414dc4992b0d17ca4d890ecba58a13482ebe9a7cdf8bbf9488a20"), SRC_SHA
SRC_LINES = s.count("\n")
assert SRC_LINES == 1397, SRC_LINES
NREP = 0


def rep(old, new, count=1):
    global s, NREP
    n = s.count(old)
    assert n == count, (old[:70], "found", n, "want", count)
    s = s.replace(old, new)
    NREP += n


def splice(opener, closer, new):
    """Replace [opener, closer) — both unique — with new."""
    global s, NREP
    assert s.count(opener) == 1, (opener[:60], s.count(opener))
    i = s.index(opener)
    if closer is None:
        j = len(s)
    else:
        assert s.count(closer) == 1, (closer[:60], s.count(closer))
        j = s.index(closer)
        assert j > i
    s = s[:i] + new + s[j:]
    NREP += 1


# ---- T1 docstring ----
rep('"""L175 scan_run.py — GENERATED by l175/build_scan.py from l150_run.py\n',
    '"""L185 rep_run.py — GENERATED by l185/build_rep.py from l175/scan_run.py\n'
    '(sha256 ' + SRC_SHA + ').\n'
    'PREREG l185/PREREG.md FIRST. R1 fresh-batch replication (rematched +\n'
    'fixed gain), R2 gain-only null, R3 signed-current twin, all on the k=24\n'
    '(cutwA) base. MODE env: static | select | work. cwd = banc/.\n'
    'L175 docstring retained below.\n\n'
    'L175 scan_run.py — GENERATED by l175/build_scan.py from l150_run.py\n')
# ---- T2 imports / mode ----
rep("import glob\nimport json\n", "import glob\nimport hashlib\nimport json\n")
rep('torch.set_num_threads(int(os.environ.get("L175_THREADS", "2")))\n'
    'MODE = os.environ["L175_MODE"]\n'
    'assert MODE in ("static", "census", "work"), MODE\n'
    'WID = int(os.environ.get("L175_WID", "0"))\n'
    'NW = int(os.environ.get("L175_NW", "1"))\n',
    'torch.set_num_threads(int(os.environ.get("L185_THREADS", "2")))\n'
    'MODE = os.environ["L185_MODE"]\n'
    'assert MODE in ("static", "select", "work"), MODE\n'
    'WID = int(os.environ.get("L185_WID", "0"))\n'
    'NW = int(os.environ.get("L185_NW", "6"))\n')
# ---- T3 seeds ----
rep('B39 = list(range(3545, 3561))       # FRESH (key-scanned absent, PREREG)\n'
    'CENSUS_SEEDS = [801, 901, 3561]     # census-only reference seeds\n'
    'SEEDS = (CENSUS_SEEDS if MODE == "census" else ANCH_BIT + B39)\n'
    'FRESH = B39\n',
    'B39 = list(range(3545, 3561))       # L175 batch: STORED, never re-sampled\n'
    'ANCH_175 = [3545]                   # L175-reproduction bit anchor (not in sample)\n'
    'B40 = list(range(3577, 3593))       # FRESH (key-scanned absent, PREREG l185)\n'
    'SEEDS = ANCH_BIT + ANCH_175 + B40   # anchors FIRST\n'
    'FRESH = B40\n'
    'assert not (set(B40) & set(B39)) and ANCH_175[0] in B39\n')
# ---- T4 output dir ----
rep('OUT = "l175"\n', 'OUT = "l185"\n')
# ---- T5 USED scan: same file set as L175 (asserted == l175/static.json) ----
rep('    if _f.startswith("l175/"):\n        continue\n    _z = np.load(_f)\n',
    '    if _f.startswith(("l175/", "l185/")):\n        continue\n    _z = np.load(_f)\n')
# ---- T6 fresh-seed absence: EVERY stored npz in the lab (banc/ + siblings),
# the L175 outputs INCLUDED; only this card's own outputs are skipped ----
rep('_fresh = set(B39) | set(CENSUS_SEEDS[2:])\n'
    'N_NPZ_SCANNED = 0\n'
    'for _f in sorted(glob.glob("**/*.npz", recursive=True)):\n'
    '    if _f.startswith("l175/"):\n'
    '        continue\n'
    '    N_NPZ_SCANNED += 1\n'
    '    for _n in zipfile.ZipFile(_f).namelist():\n',
    '_fresh = set(B40)\n'
    'N_NPZ_SCANNED = 0\n'
    'N_NPZ_SKIPPED = []\n'
    'for _f in sorted(glob.glob("../**/*.npz", recursive=True)):\n'
    '    if _f.startswith("../banc/l185/"):\n'
    '        continue\n'
    '    try:\n'
    '        _names = zipfile.ZipFile(_f).namelist()\n'
    '    except (zipfile.BadZipFile, FileNotFoundError, OSError):\n'
    '        # only a concurrently-written file of the parallel ZERO-rollout\n'
    '        # card (l184) may be unreadable; anything else is a STOP\n'
    '        assert _f.startswith("../banc/l184/"), ("unreadable npz (STOP)", _f)\n'
    '        N_NPZ_SKIPPED.append(_f)\n'
    '        continue\n'
    '    N_NPZ_SCANNED += 1\n'
    '    for _n in _names:\n')
# ---- T7 arms block ----
ARMS_BLOCK = open("l185/arms_block.py.txt").read()
splice('SC = [f"sc{r}" for r in WIN_RANKS]\n',
       '# ===================== end L175 GEN BLOCK =====================\n',
       ARMS_BLOCK)
# ---- T8 gains + anchors block (bisect_vec def stays VERBATIM) ----
GAINS_BLOCK = open("l185/gains_block.py.txt").read()
splice('assert ANCH == [11, 22, 33]\n',
       '# ---------------- rollouts ----------------\n', GAINS_BLOCK)
# ---- T9 tail ----
TAIL_BLOCK = open("l185/tail_block.py.txt").read()
splice('log(f"rollouts done {time.time()-t0:.0f}s")\n', None, TAIL_BLOCK)

# ---- residual scan (code lines only) ----
doc_end = s.index('"""', 3) + 3
code = s[doc_end:]
bad, reads175 = [], 0
for ln in code.split("\n"):
    t = ln.strip()
    if t.startswith("#"):
        continue
    c = ln.split("  #")[0]
    for tok in ("L175_", "CENSUS_SEEDS", 'MODE == "census"', '"census"',
                "raw_census", "xm_census", "gains_census", "anchors_census",
                "raw_partial"):
        if tok in c:
            bad.append((tok, ln[:90]))
    if "l175/" in c:
        # every l175 touch must be a READ (or the USED-scan skip)
        assert ("json.load(open(" in c) or ("np.load(" in c) \
            or ("startswith" in c), ("l175 non-read", ln)
        reads175 += 1
assert not bad, bad
assert reads175 >= 6, reads175
# every write goes through OUT (== "l185") or the two per-worker paths
assert s.count('OUT = "l185"\n') == 1 and 'OUT = "l175"' not in s
for need in ("def add_arm(", "def gen_init(", "def bisect_vec(", "def post_seed(",
             "def arms_for(", "def atomic_savez(", "def settle_states(",
             "def build(", "def wb(", "def pools_for(", "def add_alias(",
             "def add_base_alias(", "def signed_current(", "def _brute_paths(",
             "def _cert_gen("):
    assert s.count(need) == 1, need
# the rollout step loop is untouched: exact source lines still present once
for keep in (
        "            drive = torch.sparse.mm(WB[a], X[a]) * GAIN[a] + Iv[a]\n"
        "            if sin_t > 0:\n"
        "                drive[mech[a], 0] = drive[mech[a], 0] + sin_t\n"
        "            t = torch.relu(drive + BG)\n"
        "            t = (t + noise[a]).clamp(max=RMAX)\n"
        "            X[a] = X[a] + (DT / TAU) * (t - X[a])\n",
        "    atomic_savez(RAW_PATH, store)\n    atomic_savez(XM_PATH, XM)\n"
        "    post_seed(seed)\n"):
    assert s.count(keep) == 1, keep[:50]
open("l185/rep_run.py", "w").write(s)
py_compile.compile("l185/rep_run.py", doraise=True)
print(f"l185/rep_run.py written: {s.count(chr(10))} lines, {NREP} rep sites, "
      f"src sha {SRC_SHA[:12]}")
