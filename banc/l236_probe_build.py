"""l236_probe_build.py — generate l236_probe.py = SLICE P + probe tail.

SLICE P = l219_static.py lines 1-989 VERBATIM (a literal PREFIX, cut
immediately after the o["cert_left"] block and BEFORE the K block), which is
everything needed to have the f4wA operator, its CSR, the l169c DN->cord
block mask and the REAL left Perron vector U1 in hand.

The probe measures ONLY population-shape facts needed to write registrable
L236 predictions (family size, out-degree distribution, the menu's mean
importance, and the analytic mean identity). It must NOT print any per-cell
ratio for the actor cohort: those are the OUTCOME.
"""
import ast
import hashlib
import pathlib

SRC = pathlib.Path("l219_static.py")
TXT = SRC.read_text()
LINES = TXT.splitlines(keepends=True)
assert len(LINES) == 1672, (len(LINES), "parent line count moved (STOP)")

WHOLE = hashlib.sha256(SRC.read_bytes()).hexdigest()
assert WHOLE.startswith("fcef1ff55e0beedb"), (WHOLE, "parent sha moved (STOP)")

# PIN: the parent's OWN generated banner records its TAIL sha, and that tail
# is a literal SUFFIX of the parent -> the parent is the generated artifact.
TAIL_SRC = pathlib.Path("l219_tail.py")
TAIL_TXT = TAIL_SRC.read_text()
TAIL_SHA = hashlib.sha256(TAIL_SRC.read_bytes()).hexdigest()
BANNER = "".join(LINES[:10])
assert f"TAIL       = l219_tail.py (sha256 {TAIL_SHA[:16]})" in BANNER, \
    (TAIL_SHA[:16], "banner does not record this tail (STOP)")
assert TXT.endswith(TAIL_TXT), "l219_tail.py is not a literal SUFFIX (STOP)"
assert "PREREG l219/PREREG.md. Writes l219/static.json ONLY." in BANNER

A, B = 1, 989
SLICE_P = "".join(LINES[A - 1:B])
assert SLICE_P in TXT and TXT.startswith(SLICE_P), "slice not a PREFIX (STOP)"
SHA_P = hashlib.sha256(SLICE_P.encode()).hexdigest()
assert SLICE_P.splitlines()[0].startswith('"""GENERATED by l219_build.py')
assert SLICE_P.splitlines()[-1].strip() == "iters=400)", \
    (SLICE_P.splitlines()[-1], "slice last line (STOP)")

# STRUCTURAL audit by AST: the slice must be write-free, and must not contain
# the parent's own L219 measurement objects (decomp219 / wm_null / MENU).
TREE = ast.parse(SLICE_P)
_writes = []
for n in ast.walk(TREE):
    if isinstance(n, ast.Call):
        f = n.func
        nm = f.attr if isinstance(f, ast.Attribute) else getattr(f, "id", "")
        if nm in ("dump", "savez", "savez_compressed", "save", "to_csv",
                  "write_text", "write_bytes", "makedirs", "mkdir"):
            _writes.append(nm)
    if isinstance(n, ast.Call) and isinstance(n.func, ast.Name) \
            and n.func.id == "open":
        for a in list(n.args) + [k.value for k in n.keywords]:
            if isinstance(a, ast.Constant) and isinstance(a.value, str) \
                    and a.value != "r":
                assert a.value not in ("w", "a", "wb", "ab"), "open mode"
assert _writes == [], (_writes, "SLICE P is not write-free (STOP)")
_names = {n.name for n in ast.walk(TREE)
          if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))}
for forbidden in ("decomp219", "wm_null", "gini219"):
    assert forbidden not in _names, (forbidden, "slice reaches L219's own "
                                     "measurement machinery (STOP)")

PROBE_TAIL = '''
# =========================== L236 PROBE TAIL ===============================
# DESCRIPTION ONLY (L214): population shape facts needed to write the L236
# PREREG. No per-cell ratio for any actor is computed or printed here.
import os as _osP

_blkP = _blk_f4
_rowsP = np.where(_blkP & (src_all != GI_CARRIER))[0]
MENU_P = loc_f4[dst_all[_rowsP]].astype(np.int64)
assert MENU_P.size == _rowsP.size and int(MENU_P.min()) >= 0
log(f"[probe] menu {MENU_P.size:,} edges / {np.unique(MENU_P).size:,} cells")

# the block's DN SOURCE cells (global ids), and their local ids
_srcP = np.unique(src_all[_blkP])
_locP = loc_f4[_srcP]
assert int(_locP.min()) >= 0, "a block DN source was dropped by keep_f4"
log(f"[probe] block DN source cells: {_srcP.size:,}")

# out-degree / out-mass of each candidate IN THE OPERATOR (csr_cols == local)
_cnt = np.bincount(csr_cols, minlength=NL)
_mass = np.bincount(csr_cols, weights=jv_abs_an, minlength=NL)
_nout = _cnt[_locP]
log(f"[probe] out-degree in operator: min {_nout.min()} p05 "
    f"{np.percentile(_nout,5):.0f} med {np.median(_nout):.0f} p95 "
    f"{np.percentile(_nout,95):.0f} max {_nout.max()}")
for _b in (1, 2, 3, 5, 10, 20):
    log(f"[probe]   n_out >= {_b}: {int((_nout >= _b).sum()):,}")

# the 35 L178 actors: how many are already block DN sources?
_actloc = np.array(sorted(set(int(v) for v in ACTORS.values())), np.int64)
_inblk = np.isin(_actloc, _locP)
log(f"[probe] L178 actors {_actloc.size} distinct locals, "
    f"{int(_inblk.sum())} already block DN sources, "
    f"union size {np.union1d(_actloc, _locP).size:,}")
log(f"[probe] actor out-degrees: min {_cnt[_actloc].min()} "
    f"med {np.median(_cnt[_actloc]):.0f} max {_cnt[_actloc].max()}")

# the menu's own mean importance, and the ANALYTIC mean of the null
_muP = float(U1.mean())
_muMENU = float(U1[MENU_P].mean())
log(f"[probe] mean(u1) {_muP:.6e} | mean(u1[MENU]) {_muMENU:.6e} | "
    f"Q_menu {_muMENU/_muP:.6f}")

# ANALYTIC IDENTITY CHECK on a cell that is NOT in the actor cohort and NOT
# the carrier: E[S_draw] = m_out * mean(u1[MENU]) exactly, by linearity, so
# the weight MULTISET cannot move the null's MEAN. Probe cell = the block DN
# source with the MEDIAN out-degree (deterministic, actor-independent).
_cand = _locP[(_nout >= 10) & ~np.isin(_locP, _actloc)]
_pick = int(_cand[np.argsort(_cnt[_cand], kind="stable")[_cand.size // 2]])
_ix = np.where(csr_cols == _pick)[0]
_wp, _tp = jv_abs_an[_ix], csr_rows[_ix].astype(np.int64)
_rngP = np.random.default_rng(23601)
_Td = MENU_P[_rngP.integers(0, MENU_P.size, size=(20000, _ix.size))]
_Sd = U1[_Td] @ _wp
_pred = float(_wp.sum()) * _muMENU
log(f"[probe] analytic-mean check on local {_pick} (n_out {_ix.size}): "
    f"E[S] pred {_pred:.8e} vs draw mean {float(_Sd.mean()):.8e} "
    f"rel {abs(float(_Sd.mean())-_pred)/_pred:.3e} | draw median "
    f"{float(np.median(_Sd)):.8e} (median/mean {float(np.median(_Sd))/float(_Sd.mean()):.6f})")

# how skewed is the null for a small-degree cell? (decides the n_out floor)
for _nd in (1, 2, 3, 5, 10, 40, 69):
    _cd = _locP[_cnt[_locP] == _nd]
    if _cd.size == 0:
        continue
    _c0 = int(_cd[0])
    _i0 = np.where(csr_cols == _c0)[0]
    _T0 = MENU_P[_rngP.integers(0, MENU_P.size, size=(4000, _i0.size))]
    _S0 = U1[_T0] @ jv_abs_an[_i0]
    log(f"[probe] n_out {_nd}: null median/mean "
        f"{float(np.median(_S0))/float(_S0.mean()):.4f} | "
        f"CV {float(_S0.std())/float(_S0.mean()):.4f} | "
        f"frac draws below its own median-of-median "
        f"{float((_S0 <= np.median(_S0)).mean()):.4f}")

log(f"[probe] DONE in {time.time()-t0:.1f}s")
'''

OUT = pathlib.Path("l236_probe.py")
OUT.write_text(SLICE_P + PROBE_TAIL)
gen = hashlib.sha256(OUT.read_bytes()).hexdigest()
print(f"[build] SLICE P = l219_static.py 1-989 sha {SHA_P[:16]} "
      f"(parent whole {WHOLE[:16]}, tail {TAIL_SHA[:16]} suffix-pinned)")
print(f"[build] wrote l236_probe.py {len(OUT.read_text().splitlines())} lines "
      f"sha {gen[:16]}")
