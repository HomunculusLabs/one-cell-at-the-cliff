"""L200 builder: count-asserted ADDITIVE transform of the certified L198
harness banc/l198/twin_run.py -> banc/l200/ru2_run.py. Run from banc/.
VERBATIM from l198/twin_run.py: extraction, ladder, build()/wb()/pools_for(),
add_arm()/add_arm_multi()/add_alias()/add_base_alias()/gen_init(), the L187
arms block, the L198 twin block (selection re-pointed READ-ONLY at the frozen
l198/selection.json), settle_states, bisect_vec, the rollout step loop, store
keys, per-seed atomic checkpoints.
REPLACED: env names, seed list, output dir, the static dump (-> RU2 block:
left-matched selection + graphs + A4 wiring), gains + anchors block, tail.
ADDED: one replay-clamp line pair in each of the two rollout loops."""
import hashlib
import py_compile

SRC = "l198/twin_run.py"
s = open(SRC).read()
SRC_SHA = hashlib.sha256(s.encode()).hexdigest()
assert SRC_SHA == "c382f0c4adf0b817cf4257f986739ad15f6a82a13c5d33723bdb78848e5dd6f5", SRC_SHA
assert s.count("\n") == 1901
NREP = 0


def rep(old, new, count=1):
    global s, NREP
    n = s.count(old)
    assert n == count, (old[:70], "found", n, "want", count)
    s = s.replace(old, new)
    NREP += n


def splice(opener, closer, new):
    global s, NREP
    assert s.count(opener) == 1, (opener[:60], s.count(opener))
    i = s.index(opener)
    if closer is None:
        j = len(s)
    else:
        assert s.count(closer) == 1, (closer[:60], s.count(closer))
        j = s.index(closer)
        assert j > i
    s = s[:i] + new + s[j:]
    NREP += 1


rep('"""L198 twin_run.py — GENERATED by l198/build_twin.py from l187/relay_run.py\n',
    '"""L200 ru2_run.py — GENERATED by l200/build_ru2.py from l198/twin_run.py\n'
    '(sha256 ' + SRC_SHA + ').\n'
    'PREREG l200/PREREG.md FIRST. The ru2 (gi 70994) left-tibia phenotype: A1\n'
    'replicate, A2 left-matched twins, A3 double removal + carrier replay clamp,\n'
    'A4 wiring (static), on the k=24 (cutwA) base. MODE env: static | work.\n'
    'cwd = banc/. L198 docstring retained below.\n\n'
    'L198 twin_run.py — GENERATED by l198/build_twin.py from l187/relay_run.py\n')
rep('torch.set_num_threads(int(os.environ.get("L198_THREADS", "2")))\n'
    'MODE = os.environ["L198_MODE"]\n'
    'assert MODE in ("static", "work"), MODE\n'
    'WID = int(os.environ.get("L198_WID", "0"))\n'
    'NW = int(os.environ.get("L198_NW", "6"))\n',
    'torch.set_num_threads(int(os.environ.get("L200_THREADS", "1")))\n'
    'MODE = os.environ["L200_MODE"]\n'
    'assert MODE in ("static", "work"), MODE\n'
    'WID = int(os.environ.get("L200_WID", "0"))\n'
    'NW = int(os.environ.get("L200_NW", "6"))\n')
rep('B43 = list(range(3673, 3689))       # FRESH (key-scanned absent, PREREG l198)\n'
    'SEEDS = ANCH_BIT + ANCH_175 + ANCH_187 + B43   # anchors FIRST\n'
    'FRESH = B43\n'
    'assert not (set(B43) & (set(B39) | set(B40) | set(B41) | set(B42)))\n'
    'assert ANCH_175[0] in B39 and ANCH_187[0] in B41\n',
    'B43 = list(range(3673, 3689))       # L198 batch: STORED, never re-sampled\n'
    'ANCH_198 = [3673]                   # L198-reproduction bit anchor (not in sample)\n'
    'B44 = list(range(3705, 3721))       # FRESH (key-scanned absent, PREREG l200)\n'
    'SEEDS = ANCH_BIT + ANCH_175 + ANCH_187 + ANCH_198 + B44   # anchors FIRST\n'
    'FRESH = B44\n'
    'assert not (set(B44) & (set(B39) | set(B40) | set(B41) | set(B42) | set(B43)))\n'
    'assert ANCH_175[0] in B39 and ANCH_187[0] in B41 and ANCH_198[0] in B43\n')
rep('OUT = "l198"\n', 'OUT = "l200"\n')
rep('_fresh = set(B43)\n', '_fresh = set(B44)\n')
rep('    if _f.startswith("../banc/l198/"):\n        continue\n',
    '    if _f.startswith("../banc/l200/"):\n        continue\n')
rep('SEL_PATH = f"{OUT}/selection.json"\n',
    'SEL_PATH = "l198/selection.json"   # L200: the frozen L198 selection, READ-ONLY\n')
RU2_BLOCK = open("l200/ru2_block.py.txt").read()
splice('if MODE == "static":\n    atomic_json(f"{OUT}/static.json", dict(\n        design="L198 static pins',
       '# ===================== end L175 GEN BLOCK =====================\n', RU2_BLOCK)
GAINS_BLOCK = open("l200/gains_block.py.txt").read()
splice('assert ANCH == [11, 22, 33]\n',
       '# ---------------- rollouts ----------------\n', GAINS_BLOCK)
TAIL_BLOCK = open("l200/tail_block.py.txt").read()
splice('log(f"rollouts done {time.time()-t0:.0f}s")\n', None, TAIL_BLOCK)
# replay clamp, rollout SETTLE loop (the `X[a]` form; settle_states uses `st[a]`)
rep('            X[a] = X[a] + (DT / TAU) * ((torch.relu(drive + BG) + noise[a])\n'
    '                                        .clamp(max=RMAX) - X[a])\n'
    '            if a in CLAMPF:\n'
    '                X[a][CLAMPF[a], 0] = 0.0\n',
    '            X[a] = X[a] + (DT / TAU) * ((torch.relu(drive + BG) + noise[a])\n'
    '                                        .clamp(max=RMAX) - X[a])\n'
    '            if a in CLAMPF:\n'
    '                X[a][CLAMPF[a], 0] = 0.0\n'
    '            if a in REPLAY:   # L200: carrier <- same-step cutwA carrier value\n'
    '                X[a][REPLAY[a], 0] = X["cutwA"][CARRIER_LOC, 0]\n')
# replay clamp, rollout WINDOW loop
rep('            if a in CLAMP:\n'
    '                X[a][CLAMP[a], 0] = 0.0\n',
    '            if a in CLAMP:\n'
    '                X[a][CLAMP[a], 0] = 0.0\n'
    '            if a in REPLAY:   # L200: carrier <- same-step cutwA carrier value\n'
    '                X[a][REPLAY[a], 0] = X["cutwA"][CARRIER_LOC, 0]\n')
# cutwA must be stepped FIRST for the replay read to be the same-step value
rep('for seed in SEEDS:\n    ARMS = arms_for(seed)\n',
    'for seed in SEEDS:\n    ARMS = arms_for(seed)\n'
    '    assert ARMS[0] == "cutwA" and all(a not in REPLAY or i > 0 for i, a in enumerate(ARMS))\n')
rep('    if f"mm_cutwA_{seed}" in store and f"xmean_cutwA_{seed}" in XM:\n',
    '    if all(f"mm_{_a}_{seed}" in store and f"xmean_{_a}_{seed}" in XM for _a in ARMS):\n')

doc_end = s.index('"""', 3) + 3
code = s[doc_end:]
bad = []
for ln in code.split("\n"):
    if ln.strip().startswith("#"):
        continue
    c = ln.split("  #")[0]
    for tok in ("L198_", 'OUT = "l198"', "set(B43)\n"):
        if tok in c:
            bad.append((tok, ln[:90]))
    if "l198/" in c or "l187/" in c or "l190/" in c or "l185/" in c or "l175/" in c:
        assert ("json.load(open(" in c) or ("np.load(" in c) or ("startswith" in c) \
            or ("pd.read_csv(" in c) or ('SEL_PATH = "l198/selection.json"' in c), ("non-read", ln)
assert not bad, bad
assert s.count('OUT = "l200"\n') == 1
for keep in (
        "            drive = torch.sparse.mm(WB[a], X[a]) * GAIN[a] + Iv[a]\n"
        "            if sin_t > 0:\n"
        "                drive[mech[a], 0] = drive[mech[a], 0] + sin_t\n"
        "            t = torch.relu(drive + BG)\n"
        "            t = (t + noise[a]).clamp(max=RMAX)\n"
        "            X[a] = X[a] + (DT / TAU) * (t - X[a])\n"
        "            if a in CLAMP:\n"
        "                X[a][CLAMP[a], 0] = 0.0\n",
        "    atomic_savez(RAW_PATH, store)\n    atomic_savez(XM_PATH, XM)\n"
        "    post_seed(seed)\n"):
    assert s.count(keep) == 1, keep[:50]
assert s.count('X[a][REPLAY[a], 0] = X["cutwA"][CARRIER_LOC, 0]\n') == 2
for need in ("def add_arm(", "def gen_init(", "def bisect_vec(", "def post_seed(",
             "def arms_for(", "def settle_states(", "def select_twin(", "def select_left(",
             "def _a4(", "def _replay_cert("):
    assert s.count(need) == 1, need
open("l200/ru2_run.py", "w").write(s)
py_compile.compile("l200/ru2_run.py", doraise=True)
print(f"l200/ru2_run.py written: {s.count(chr(10))} lines, {NREP} rep sites, src sha {SRC_SHA[:12]}")
