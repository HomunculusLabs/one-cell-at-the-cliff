"""l237_build.py — generate l237_static.py from VERBATIM slices of
l219_static.py, l236_mid1.py/l236_mid2.py (a prior card's CERTIFICATION BLOCK
re-used as a source slice, L225's law) and l231_tail.py, plus l237_tail.py.

Layout (every SLICE is byte-for-byte from its source):

  SLICE P    = l219_static.py 1-989      (prefix: data, annotations, pools,
                                          f4wA, CSR, CERT-F4/REW/178/NULL/
                                          206/MV/LEFT, the l169c block mask,
                                          the certified left Perron vector U1)
  SLICE MID1 = l236_mid1.py              (read-only fingerprints, S219/S207,
                                          the homolog gi DERIVED from l207)
  SLICE H    = l219_static.py 1231-1281  (gini219/_rank219/spear219/decomp219)
  SLICE R    = l219_static.py 1284-1309  (the carrier's 69 out-edges,
                                          identities (I) and (II))
  SLICE T    = l219_static.py 1459-1474  (the contribution table / ginis)
  SLICE C    = l219_static.py 1476-1501  (the 35-actor cohort loop + helpers)
  SLICE MID2 = l236_mid2.py              (CERT-236A, CERT-236B)
  SLICE M    = l219_static.py 1536-1545  (the MENU)
  SLICE D    = l231_tail.py 429-450      (midrank / spearman, L221)
  TAIL       = l237_tail.py              (this card's own measurement + write)

The parent's ~370 s per-draw eigendecomposition loop is CUT (L226/L235: a cost
slice is an INTERVENTION until measured). SLICE MID2's CERT-236A/B are the
measurement that admits the cut, re-run here as the code that actually
produced l219/static.json.
"""
import ast
import hashlib
import pathlib

# ---- sources ---------------------------------------------------------------
P_SRC = pathlib.Path("l219_static.py")
P_TXT = P_SRC.read_text()
P_LINES = P_TXT.splitlines(keepends=True)
assert len(P_LINES) == 1672, (len(P_LINES), "parent line count moved (STOP)")
P_WHOLE = hashlib.sha256(P_SRC.read_bytes()).hexdigest()
assert P_WHOLE.startswith("fcef1ff55e0beedb"), (P_WHOLE, "parent sha (STOP)")

# PIN 1: the parent's OWN generated banner records its TAIL sha, and that tail
# is a literal SUFFIX of the parent -> the parent IS the script l219_build.py
# produced. DISCLOSED (L236): l219/static.json stores no banner of its own
# (its "banner" key carries L210's), so this pin + the float-equality coverage
# in SLICE MID2 is what identifies the parent.
PT_SRC = pathlib.Path("l219_tail.py")
PT_TXT = PT_SRC.read_text()
PT_SHA = hashlib.sha256(PT_SRC.read_bytes()).hexdigest()
BANNER = "".join(P_LINES[:10])
assert f"TAIL       = l219_tail.py (sha256 {PT_SHA[:16]})" in BANNER, \
    (PT_SHA[:16], "banner does not record this tail (STOP)")
assert P_TXT.endswith(PT_TXT), "l219_tail.py is not a literal SUFFIX (STOP)"
assert "PREREG l219/PREREG.md. Writes l219/static.json ONLY." in BANNER
for _pin in ("CERT-HEAD1 = l151_static.py lines 1-319 VERBATIM",
             "CERT-210M  = l210_tail.py lines 1-326 VERBATIM"):
    assert _pin in BANNER, (_pin, "inherited chain moved (STOP)")

RANGES = dict(P=(1, 989), H=(1231, 1281), R=(1284, 1309), T=(1459, 1474),
              C=(1476, 1501), M=(1536, 1545))
FIRST_LAST = dict(
    P=('"""GENERATED by l219_build.py — do not edit by hand.', "iters=400)"),
    H=("def gini219(x):", "mean_u=mu, mean_target_u_bare=mq, ident_rel=res)"),
    R=("# ---------------- the REAL wiring: the carrier's 69 out-edges "
       "---------------",
       '"log1p out-mass and is reported for continuity only"))'),
    T=("# ---------------- Q219-2 (leg a): the per-target contribution table "
       "---------", 'f"{sum(t[\'share_of_S\'] for t in TOP10):.4f}")'),
    C=("COH219 = {}",
       "return float(np.mean([COH219[k][key] < val for k in _fam]))"),
    M=("# ---------------- Q219-3 (leg b): the WEIGHT-MATCHED semi-analytic "
       "nulls ---", 'f"({np.unique(MENU).size:,} distinct cells)")'))

SLICES, SHAS = {}, {}
for k, (a, b) in RANGES.items():
    s = "".join(P_LINES[a - 1:b])
    assert s in P_TXT, (k, "slice is not a literal substring (STOP)")
    SLICES[k] = s
    SHAS[k] = hashlib.sha256(s.encode()).hexdigest()
    fl, ll = FIRST_LAST[k]
    assert s.splitlines()[0].strip() == fl.strip(), (k, "first line")
    assert s.splitlines()[-1].strip() == ll.strip(), (k, "last line")
assert P_TXT.startswith(SLICES["P"]), "SLICE P is not a literal PREFIX (STOP)"

# ---- line-set audit: DISJOINT, ordered, and the CUT region owns the parent's
# ---- per-draw loop and its writer (STRUCTURALLY, by AST — never a token scan)
_used, _prev = set(), 0
for k in ("P", "H", "R", "T", "C", "M"):
    a, b = RANGES[k]
    assert a > _prev, (k, "slices out of order or overlapping (STOP)")
    _prev = b
    _used |= set(range(a, b + 1))
N_KEPT = len(_used)
CUT = sorted(set(range(1, len(P_LINES) + 1)) - _used)
N_CUT = len(CUT)
assert N_KEPT + N_CUT == len(P_LINES)
_cut_txt = "".join(P_LINES[i - 1] for i in CUT)
for _tok in ("wm_null(MENU, 2000, 21901)", "json.dump", "Q219_3_weight_matched",
             "Q219_4_draw_distributions", "cert_wmult"):
    assert _tok in _cut_txt, (_tok, "cut region does not own it (STOP)")

# every KEPT slice must be WRITE-FREE, proven on its own AST
_W = ("dump", "write", "savez", "savez_compressed", "save", "to_csv",
      "makedirs", "mkdir", "open")


def _write_sites(src):
    hits = []
    for n in ast.walk(ast.parse(src)):
        if isinstance(n, ast.Call):
            f = n.func
            nm = (f.attr if isinstance(f, ast.Attribute)
                  else f.id if isinstance(f, ast.Name) else "")
            if nm in _W:
                hits.append((nm, getattr(n, "lineno", -1)))
    return hits


for k in ("H", "R", "T", "C", "M"):
    _h = [x for x in _write_sites(SLICES[k]) if x[0] != "open"]
    assert not _h, (k, _h, "kept slice is not write-free (STOP)")

# SLICE P is the parent's whole prefix: it opens prior artifacts read-only.
# Assert it contains no DUMP/SAVE and no makedirs (the parent writes only in
# its cut tail).
_hp = [x for x in _write_sites(SLICES["P"])
       if x[0] in ("dump", "savez", "savez_compressed", "to_csv", "makedirs",
                   "mkdir")]
assert not _hp, (_hp, "SLICE P writes (STOP)")

# ---- the re-used CERTIFICATION BLOCK slices (L225) -------------------------
M1_SRC = pathlib.Path("l236_mid1.py")
M2_SRC = pathlib.Path("l236_mid2.py")
M1_TXT, M2_TXT = M1_SRC.read_text(), M2_SRC.read_text()
M1_SHA = hashlib.sha256(M1_SRC.read_bytes()).hexdigest()
M2_SHA = hashlib.sha256(M2_SRC.read_bytes()).hexdigest()
assert M1_SHA.startswith("aedff520261fecaf"), (M1_SHA, "MID1 sha (STOP)")
assert M2_SHA.startswith("78e30778f3a1d32a"), (M2_SHA, "MID2 sha (STOP)")
# these two slices are a literal SUBSTRING of l236_static.py = proof they are
# the bytes that ran inside the certified parent card.
L236_TXT = pathlib.Path("l236_static.py").read_text()
L236_SHA = hashlib.sha256(pathlib.Path("l236_static.py").read_bytes()).hexdigest()
assert L236_SHA.startswith("033665492b93baf9"), (L236_SHA, "l236 sha (STOP)")
assert M1_TXT in L236_TXT, "MID1 did not run inside l236_static.py (STOP)"
assert M2_TXT in L236_TXT, "MID2 did not run inside l236_static.py (STOP)"
for _nm, _t in (("MID1", M1_TXT), ("MID2", M2_TXT)):
    _h = [x for x in _write_sites(_t)
          if x[0] in ("dump", "savez", "to_csv", "makedirs", "mkdir")]
    assert not _h, (_nm, _h, "re-used cert block writes (STOP)")
# MID2 must still be the CERT block, structurally: it defines _leaves236 and
# assigns o_cert236a / o_cert236b, and nothing else at module level.
_m2 = ast.parse(M2_TXT)
_m2_def = [n.name for n in _m2.body if isinstance(n, ast.FunctionDef)]
assert _m2_def == ["_leaves236"], (_m2_def, "MID2 defines more (STOP)")
_m2_keys = set()
for n in _m2.body:
    if isinstance(n, ast.Assign):
        for t in n.targets:
            if isinstance(t, ast.Name):
                _m2_keys.add(t.id)
assert {"o_cert236a", "o_cert236b"} <= _m2_keys, (_m2_keys, "MID2 (STOP)")

D_SRC = pathlib.Path("l231_tail.py")
D_LINES = D_SRC.read_text().splitlines(keepends=True)
D_WHOLE = hashlib.sha256(D_SRC.read_bytes()).hexdigest()
assert D_WHOLE.startswith("879539c97fbe4d93"), (D_WHOLE, "l231_tail (STOP)")
SLICE_D = "".join(D_LINES[428:450])
D_SHA = hashlib.sha256(SLICE_D.encode()).hexdigest()
assert D_SHA.startswith("887a396073745d80"), \
    (D_SHA, "SLICE D is not the slice L233/L235 used (STOP)")
_dd = ast.parse(SLICE_D)
assert [n.name for n in _dd.body if isinstance(n, ast.FunctionDef)] \
    == ["midrank", "spearman"], "SLICE D defines more than expected (STOP)"
assert "mergesort" in SLICE_D, "SLICE D lost the stable-sort assertion (STOP)"

# ---- this card's own tail --------------------------------------------------
T_SRC = pathlib.Path("l237_tail.py")
T_TXT = T_SRC.read_text()
T_SHA = hashlib.sha256(T_SRC.read_bytes()).hexdigest()
_tw = [x for x in _write_sites(T_TXT) if x[0] in ("dump", "makedirs")]
assert sorted(set(x[0] for x in _tw)) == ["dump", "makedirs"], (_tw, "tail")
assert len([x for x in _tw if x[0] == "dump"]) == 1, (_tw, "one write (STOP)")
assert "l237/static.json" in T_TXT
for _bad in ("l219/static.json\", \"w", "l236/static.json\", \"w",
             "subprocess", "systemctl"):
    assert _bad not in T_TXT, (_bad, "tail touches something it must not")

# ---- assemble --------------------------------------------------------------
HEAD = f'''"""GENERATED by l237_build.py — do not edit by hand.
SLICE P    = l219_static.py lines 1-989 VERBATIM (sha256 {SHAS["P"][:16]}; parent whole-file {P_WHOLE[:16]}).
SLICE MID1 = l236_mid1.py VERBATIM (sha256 {M1_SHA[:16]}).
SLICE H    = l219_static.py lines 1231-1281 VERBATIM (sha256 {SHAS["H"][:16]}).
SLICE R    = l219_static.py lines 1284-1309 VERBATIM (sha256 {SHAS["R"][:16]}).
SLICE T    = l219_static.py lines 1459-1474 VERBATIM (sha256 {SHAS["T"][:16]}).
SLICE C    = l219_static.py lines 1476-1501 VERBATIM (sha256 {SHAS["C"][:16]}).
SLICE MID2 = l236_mid2.py VERBATIM (sha256 {M2_SHA[:16]}; a literal substring of l236_static.py {L236_SHA[:16]}).
SLICE M    = l219_static.py lines 1536-1545 VERBATIM (sha256 {SHAS["M"][:16]}).
SLICE D    = l231_tail.py lines 429-450 VERBATIM (sha256 {D_SHA[:16]}; source whole-file {D_WHOLE[:16]}).
TAIL       = l237_tail.py (sha256 {T_SHA[:16]}).
PARENT PIN = l219_tail.py (sha256 {PT_SHA[:16]}) recorded in the parent's own banner AND a literal SUFFIX of it.
CUT        = {N_CUT} parent lines (the per-draw eigendecomposition loop, Q219-3/Q219-4, the writer); {N_KEPT} kept.
PREREG l237/PREREG.md. Writes l237/static.json ONLY.
"""
'''
OUT = (HEAD + SLICES["P"] + M1_TXT + SLICES["H"] + SLICES["R"] + SLICES["T"]
       + SLICES["C"] + M2_TXT + SLICES["M"] + "\n\n" + SLICE_D + "\n"
       + T_TXT)
DST = pathlib.Path("l237_static.py")
DST.write_text(OUT)
O_SHA = hashlib.sha256(DST.read_bytes()).hexdigest()

# ---- post-assembly audits on the GENERATED file ---------------------------
G_TXT = DST.read_text()
assert SLICES["P"] in G_TXT and M1_TXT in G_TXT and M2_TXT in G_TXT
assert SLICE_D in G_TXT and G_TXT.endswith(T_TXT)
_g = ast.parse(G_TXT)
_imp = set()
for n in ast.walk(_g):
    if isinstance(n, ast.Import):
        _imp |= {a.name.split(".")[0] for a in n.names}
    elif isinstance(n, ast.ImportFrom) and n.module:
        _imp.add(n.module.split(".")[0])
assert not (_imp & {"l219_static", "l236_static", "l231_tail", "brain",
                    "serve", "bridge", "senses", "mood"}), \
    (_imp, "L175: a lab/live module is IMPORTED (STOP)")
_gw = [x for x in _write_sites(G_TXT)
       if x[0] in ("dump", "savez", "to_csv", "makedirs", "mkdir")]
assert sorted(set(x[0] for x in _gw)) == ["dump", "makedirs"], (_gw, "writes")
assert len([x for x in _gw if x[0] == "dump"]) == 1, (_gw, "ONE write (STOP)")

print(f"[l237_build] wrote l237_static.py {len(G_TXT.splitlines())} lines "
      f"sha256 {O_SHA[:16]}")
print(f"[l237_build] slices P {SHAS['P'][:16]} H {SHAS['H'][:16]} "
      f"R {SHAS['R'][:16]} T {SHAS['T'][:16]} C {SHAS['C'][:16]} "
      f"M {SHAS['M'][:16]} | MID1 {M1_SHA[:16]} MID2 {M2_SHA[:16]} "
      f"D {D_SHA[:16]} TAIL {T_SHA[:16]}")
print(f"[l237_build] kept {N_KEPT} parent lines, CUT {N_CUT}")
