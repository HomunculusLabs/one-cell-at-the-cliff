"""l205_build.py — generate l205_static.py from certified verbatim slices.

l205_static.py = banner
               + HEAD1 : l151_static.py lines 1-319      (BYTE-FOR-BYTE)
               + PRE   : 6 lines defining the output dict `o` that HEAD2 writes
               + HEAD2 : l178_tail.py lines 22-83         (BYTE-FOR-BYTE)
               + TAIL  : l205_tail.py

CERT: each head slice is asserted to be a LITERAL PREFIX/SLICE of its source
file, its sha256 recorded, and audited for forbidden tokens (file writes, lab
script imports) so running the generated script cannot touch l151's or l178's
stored artifacts. The L175 lesson: a lab run script is a SCRIPT, never a
library, and must never be imported.
"""
import hashlib
import pathlib

H1_SRC = pathlib.Path("l151_static.py")
H2_SRC = pathlib.Path("l178_tail.py")
TAIL_SRC = pathlib.Path("l205_tail.py")
OUT = pathlib.Path("l205_static.py")
N_H1 = 319
H2_LO, H2_HI = 22, 83          # 1-indexed inclusive

h1_text = H1_SRC.read_text()
h1_lines = h1_text.splitlines(keepends=True)
assert len(h1_lines) >= N_H1, (len(h1_lines), "l151_static.py too short")
head1 = "".join(h1_lines[:N_H1])
assert h1_text.startswith(head1), "HEAD1 slice is not a literal prefix"

h2_text = H2_SRC.read_text()
h2_lines = h2_text.splitlines(keepends=True)
assert len(h2_lines) >= H2_HI, (len(h2_lines), "l178_tail.py too short")
head2 = "".join(h2_lines[H2_LO - 1:H2_HI])
assert head2 in h2_text, "HEAD2 slice is not a literal slice"
assert head2.startswith("FLOOR = 4\n"), head2[:40]
assert head2.rstrip().endswith("del _z"), head2[-60:]

for name, blob in (("HEAD1", head1), ("HEAD2", head2)):
    for bad in ('"w"', "'w'", "import l1", "import l9", "savez", "to_csv",
                "json.dump", "write_text"):
        assert bad not in blob, f"{name} contains forbidden token {bad!r}"

PRE = (
    "\n# ---- L205 PRE (the only hand-written lines between the two certified"
    " slices):\n"
    "# HEAD2 writes o['cert_f4'] and o['gains'], so the dict must exist first.\n"
    "o = {\"design\": \"L205 floor-4 handedness static (L175 G4 unrun half): \"\n"
    "     \"per-side Ti/Tr pool in-mass on base vs floor-4 substrates vs a \"\n"
    "     \"membership-permutation handedness null. Zero rollouts, zero \"\n"
    "     \"settles, zero dynamics.\",\n"
    "     \"prereg\": \"l205/PREREG.md\"}\n\n")

tail = TAIL_SRC.read_text()
sh = {k: hashlib.sha256(v.encode()).hexdigest()
      for k, v in (("head1", head1), ("head2", head2), ("tail", tail))}

banner = (
    '"""GENERATED by l205_build.py — do not edit by hand.\n'
    f"HEAD1 = l151_static.py lines 1-{N_H1} VERBATIM (sha256 {sh['head1'][:16]}).\n"
    f"HEAD2 = l178_tail.py lines {H2_LO}-{H2_HI} VERBATIM "
    f"(sha256 {sh['head2'][:16]}).\n"
    f"TAIL  = l205_tail.py (sha256 {sh['tail'][:16]}).\n"
    'PREREG l205/PREREG.md. Writes l205/static.json ONLY.\n'
    '"""\n')

body = banner + head1 + PRE + head2 + tail
OUT.write_text(body)
written = OUT.read_text()
assert written == body
for name, blob in (("HEAD1", head1), ("HEAD2", head2), ("TAIL", tail)):
    assert blob in written, f"generated file lost {name}"
print(f"wrote {OUT} ({len(written.splitlines())} lines)")
for k, v in sh.items():
    print(f"{k} sha256 {v}")
