"""l169c_build.py — generate l169c_static.py as a 1-SITE ADDITIVE transform of
l151_static.py: lines 1-319 VERBATIM (so every L151/L142/L134 pin re-runs as
free certification) + the l169c_tail.py block. House form inherited from
l169b_build.py. Guards: splice anchor count-asserted, residual scan refuses any
surviving WRITE to the l151 artifact, single json.dump target asserted,
py_compile. PREREG: l169c/PREREG.md (registered before any computation).
"""
import py_compile
import sys

SRC = "l151_static.py"
TAIL = "l169c_tail.py"
OUT = "l169c_static.py"
ANCHOR = "# ---------------- verdict ----------------"

src = open(SRC).read().split("\n")
hits = [i for i, l in enumerate(src) if l.rstrip() == ANCHOR]
assert len(hits) == 1, ("splice anchor count", len(hits))
cut = hits[0]
assert cut == 319, ("anchor moved", cut)          # l151_static.py line 320
head = "\n".join(src[:cut])
tail = open(TAIL).read()

# head must still contain the pins this stage relies on (certification by reuse)
for pin in ("assert int(sel_out_n.sum()) == 80",
            "183.96376182027785",
            "assert int(sel_in_n.sum()) == 13 and int(sel_in_wA.sum()) == 13",
            "assert int(T70.sum()) == 70 and int(T10.sum()) == 10",
            "assert int(ng_desc[24]) == GI and int(ng_desc[25]) == 319",
            "assert int((emask_wA & e_drop_all).sum()) == 93"):
    assert head.count(pin) == 1, ("lost head pin", pin)
# symbols the tail consumes must be defined in the head
for sym in ("res_s1", "res_s2", "res_s3", "POOL_G", "tier_of_dst",
            "cord_of_dst", "mot_rows", "side_m", "mgi", "nt_map", "dn_new_g",
            "glut_desc", "win24_mask", "motor_G", "T70", "T10", "emask_wA",
            "emask_n", "vals_all", "dn_into", "dn_proj", "cord_mask"):
    assert f"{sym} " in head or f"{sym}[" in head or f"{sym}=" in head, sym

banner = (f'"""GENERATED by l169c_build.py — do not edit by hand.\n'
          f'Head = {SRC} lines 1-{cut} VERBATIM; tail = {TAIL}.\n'
          f'PREREG l169c/PREREG.md. Writes l169c/static.json ONLY.\n"""\n')
out = banner + head + "\n" + tail
open(OUT, "w").write(out)

# ---------------- residual scan (l126 rule: whitelist by LINE CONTEXT) --------
bad = []
in_doc = False
for n, ln in enumerate(out.split("\n"), 1):
    s = ln.strip()
    if s.startswith('"""') or s.endswith('"""'):
        # docstring delimiter lines toggle; treat as prose
        in_doc = not in_doc if s.count('"""') == 1 else in_doc
        continue
    if in_doc or s.startswith("#") or not s:
        continue
    if "l151/static.json" in s and "json.load" not in s:
        bad.append((n, s))
    if "l146/static.json" in s and "json.load" not in s:
        bad.append((n, s))
assert not bad, ("residual WRITE to a prior artifact", bad)
assert out.count("json.dump") == 1, out.count("json.dump")
assert 'json.dump(o9, open("l169c/static.json", "w")' in out
assert out.count('open("l169c/static.json", "w")') == 1
# the tail is additive: the head is byte-identical to the source prefix
assert out[len(banner):len(banner) + len(head)] == head

py_compile.compile(OUT, doraise=True)
print(f"built {OUT}: head {cut} lines verbatim + tail {len(tail.split(chr(10)))} "
      f"lines; residual scan CLEAN; py_compile OK", file=sys.stderr)
print(f"lines_total={len(out.split(chr(10)))}")
