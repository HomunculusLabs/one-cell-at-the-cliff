def bisect_af_mean(g):
    afs = []
    for s in ANCH:
        st = settle_states(s, dict(full=G_NEW, b65=G65, h65=GH, cut=g))
        afs.append(float((st["cut"] > 0.05).float().mean()))
    return float(np.mean(afs))


