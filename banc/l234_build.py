"""l234_build.py — generate l234_static.py from TWO pieces.

  SLICE A = l218_static.py lines 1-1691 VERBATIM — a literal PREFIX of the
            GENERATED parent, cut immediately before L218's own
            predictions/writer block. This carries, as the code that
            ACTUALLY produced l218/static.json: CERT-HEAD1..4, CERT-210M,
            CERT-218T (1224), CERT-W50 (1010), CERT-DEFLV, the 50-depth
            walks, Q218-1/2/3 and the per-draw A2K/U2K arrays.
  TAIL    = l234_tail.py — L234's body.

PINS (all three asserted, none hand-typed as a fact about bytes):
  1. l218_static.py's first 10 lines == l218/static.json["banner"], i.e. the
     generated script's own banner as RECORDED INSIDE the artifact it made.
  2. l218_tail.py's whole-file sha256 == the TAIL sha the banner records,
     AND l218_tail.py is a literal SUFFIX of l218_static.py.
  3. SLICE A is a literal PREFIX of l218_static.py and is AST-PROVEN
     write-free; the CUT lines are audited STRUCTURALLY by AST (L226/L233:
     never a bare-token scan, which fires on the slice's own prose).
"""
import ast
import hashlib
import json
import pathlib

PAR = pathlib.Path("l218_static.py")
PTAIL = pathlib.Path("l218_tail.py")
TAIL_SRC = pathlib.Path("l234_tail.py")
OUT = pathlib.Path("l234_static.py")
CUT = 1691

par_txt = PAR.read_text()
par_lines = par_txt.splitlines(keepends=True)
assert len(par_lines) == 1763, ("parent line count", len(par_lines))
sliceA = "".join(par_lines[:CUT])
cut_src = "".join(par_lines[CUT:])
assert par_txt.startswith(sliceA), "SLICE A is not a literal PREFIX (STOP)"
assert sliceA + cut_src == par_txt, "slice/cut do not reconstruct the parent"
shaA = hashlib.sha256(sliceA.encode()).hexdigest()
sha_par = hashlib.sha256(par_txt.encode()).hexdigest()
ptail = PTAIL.read_text()
sha_ptail = hashlib.sha256(ptail.encode()).hexdigest()
tail = TAIL_SRC.read_text()
sha_tail = hashlib.sha256(tail.encode()).hexdigest()

# ---- PIN 1: the artifact's own record of the script that made it ----------
S218 = json.loads(pathlib.Path("l218/static.json").read_text())
banner = "".join(par_lines[:10])
assert banner == S218["banner"], \
    "l218_static.py's banner != the banner stored INSIDE l218/static.json -> " \
    "the parent script MOVED since it produced the artifact (STOP)"
print("[pin1] GREEN l218_static.py banner == l218/static.json['banner']")

# ---- PIN 2: the parent's tail, by the banner's own sha + suffix ------------
assert f"TAIL       = l218_tail.py (sha256 {sha_ptail[:16]})." in banner, \
    (sha_ptail[:16], "l218_tail.py MOVED since l218_static.py was generated")
assert par_txt.endswith(ptail), "l218_tail.py is not a SUFFIX of the parent"
print(f"[pin2] GREEN l218_tail.py sha {sha_ptail[:16]} == the banner's "
      f"recorded TAIL sha, and is a literal SUFFIX of the parent")

# ---- PIN 3: SLICE A boundary anchors, DERIVED from the parent's own lines --
assert par_lines[CUT - 1].rstrip("\n") == '_el("Q218-3")', \
    ("SLICE A last line", par_lines[CUT - 1])
assert par_lines[CUT].strip() == "", ("cut first line", par_lines[CUT])
assert par_lines[CUT + 1].startswith("# ---------------- predictions"), \
    ("cut second line", par_lines[CUT + 1])
assert par_lines[0].startswith('"""GENERATED by l218_build.py'), "parent head"

# the slice must CONTAIN every gate this card inherits ...
for tok in ("CERT-218T", "CERT-W50", "CERT-DEFLV", "CERT-206", "CERT-MV",
            "CERT-LEFT", "CERT-REBUILD", "CERT-178", "CERT-NULL", "CERT-F4",
            "CERT-REW", "def mv(x, jv, ls, ld):", "def pi_dir(",
            "def lam2_defl(", "def coeff(", "def defl_pair", "def defl_resid",
            "DEEP = 50", '_pred_e = np.array(', "_cf_relerr = [",
            'o["Q218_1_primary"]', 'o["Q218_2_rate"]', 'o["Q218_3_u2"]',
            "A2K = np.array(A2K)"):
    assert tok in sliceA, ("SLICE A lost", tok)
# ... and must NOT reach into the parent's own predictions/writer block.
# NEGATIVE AUDIT IS STRUCTURAL, BY AST — a bare-token scan fires on the
# slice's own PROSE (l218_tail.py's header comment literally says "the
# parent's json.dump is excluded by the forbidden-token audit"); that trap
# has now bitten seven times, so this card does not own a token list.
treeA = ast.parse(sliceA)

# ---- STRUCTURAL audits by AST (never a bare-token scan) -------------------
treeA = ast.parse(sliceA)


def write_sites(tree):
    """every Call that opens a file for writing or dumps json, by AST."""
    hits = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            fn = node.func
            name = (fn.attr if isinstance(fn, ast.Attribute)
                    else getattr(fn, "id", ""))
            if name in ("dump", "savez", "savez_compressed", "to_csv",
                        "savetxt", "write_text", "write_bytes"):
                hits.append((name, node.lineno))
            if name == "open":
                mode = ""
                if len(node.args) > 1 and isinstance(node.args[1], ast.Constant):
                    mode = str(node.args[1].value)
                for kw in node.keywords:
                    if kw.arg == "mode" and isinstance(kw.value, ast.Constant):
                        mode = str(kw.value.value)
                if any(c in mode for c in "wax+"):
                    hits.append((f"open({mode!r})", node.lineno))
            if name == "makedirs":
                hits.append(("makedirs", node.lineno))
    return hits


assert write_sites(treeA) == [], ("SLICE A is NOT write-free", write_sites(treeA))
# structural proof that the slice stops BEFORE the parent's verdict keys
sliceA_okeys = set()
for node in ast.walk(treeA):
    if isinstance(node, ast.Assign):
        for t in node.targets:
            if (isinstance(t, ast.Subscript) and isinstance(t.value, ast.Name)
                    and t.value.id == "o"
                    and isinstance(t.slice, ast.Constant)):
                sliceA_okeys.add(t.slice.value)
assert sliceA_okeys.isdisjoint({"predictions", "amendments", "limitations",
                                "priors_readonly",
                                "rows_per_draw_recomputed"}), \
    ("SLICE A assigns a verdict key", sorted(sliceA_okeys))
print(f"[pin3] GREEN SLICE A is a literal PREFIX, AST-PROVEN write-free, "
      f"assigns {len(sliceA_okeys)} o[...] measurement keys and none of the "
      f"parent's five verdict keys, {CUT} lines, sha256 {shaA[:16]}")

# the CUT lines, audited STRUCTURALLY: they must OWN the parent's writer
tree_cut = ast.parse(cut_src)
cut_writes = [n for n, _ in write_sites(tree_cut)]
assert "dump" in cut_writes and "makedirs" in cut_writes, \
    ("the cut must contain the parent's writer", cut_writes)
cut_assigns = set()
for node in ast.walk(tree_cut):
    if isinstance(node, ast.Assign):
        for t in node.targets:
            if (isinstance(t, ast.Subscript) and isinstance(t.value, ast.Name)
                    and t.value.id == "o"
                    and isinstance(t.slice, ast.Constant)):
                cut_assigns.add(t.slice.value)
assert cut_assigns == {"predictions", "amendments", "limitations",
                       "priors_readonly", "rows_per_draw_recomputed"}, \
    ("the cut's o[...] assignments", sorted(cut_assigns))
print(f"[cut] GREEN {len(cut_src.splitlines())} cut lines own exactly the "
      f"parent's writer and o[...] keys {sorted(cut_assigns)}")

# ---- the TAIL: no certified def re-transcribed, this card's gates present --
tree_tail = ast.parse(tail)
for fn in ("def jmatvec", "def reach(", "def power_iter(", "def sweep_actor",
           "def build_sub", "def mv(", "def pi_dir(", "def lam2_defl(",
           "def coeff(", "def defl_pair(", "def defl_resid("):
    assert fn not in tail, f"TAIL re-transcribes certified {fn!r} (L85)"
for need in ("CERT-234A", "CERT-234B", "CERT-234C", "def defl_multi",
             "def defl_resid_multi", "def _lc234", 'out234["Q1_two_mode"]',
             'out234["Q2_K2_null"]', 'out234["Q3_compose"]',
             "RESOLVED3", "K2K", "_compose_rel"):
    assert need in tail, f"TAIL lost {need!r}"
# L175: no lab module imported anywhere in the generated file
body = sliceA + "\n\n" + tail
tree_all = ast.parse(body)
bad = []
for node in ast.walk(tree_all):
    if isinstance(node, ast.Import):
        bad += [a.name for a in node.names
                if a.name.startswith(("l1", "l2", "l9"))]
    elif isinstance(node, ast.ImportFrom):
        if node.module and node.module.startswith(("l1", "l2", "l9")):
            bad.append(node.module)
assert not bad, ("a lab module is IMPORTED (L175)", bad)
# exactly ONE write site in the whole generated script, and it is ours
ws = write_sites(tree_all)
dumps = [w for w in ws if w[0] == "dump"]
opens = [w for w in ws if w[0].startswith("open(")]
mkd = [w for w in ws if w[0] == "makedirs"]
assert len(dumps) == 1 and len(opens) == 1 and len(mkd) == 1, \
    ("write sites", ws)
assert 'json.dump(out234, open("l234/static.json", "w"), indent=1)' in tail, \
    "the single write is not the registered one"
print(f"[ast] GREEN exactly one write site (l234/static.json), one makedirs, "
      f"no lab module imported")

OUT.write_text(body)
assert OUT.read_text() == body
assert body.startswith(sliceA) and body.endswith(tail)
print(f"wrote {OUT} ({len(body.splitlines())} lines)")
print(f"SLICE A   l218_static.py 1-{CUT} sha256 {shaA}")
print(f"PARENT    l218_static.py whole    sha256 {sha_par}")
print(f"PARENT    l218_tail.py   whole    sha256 {sha_ptail}")
print(f"TAIL      l234_tail.py            sha256 {sha_tail}")
print(f"GENERATED sha256 {hashlib.sha256(body.encode()).hexdigest()}")
