"""L175 builder: count-asserted ADDITIVE transform of banc/l150_run.py
-> banc/l175/scan_run.py. Run from banc/ (cwd law). Every rep is
count-pinned; long blocks are spliced on UNIQUE OPENERS (l122 law);
inserted blocks sit inside the original def-order (l131 law).

What stays VERBATIM from l150_run.py: extraction, ladder, every
lineage arm's graph + per-arm plumbing (incl. cutwA / cutng25 / cutng25p),
settle_states body, the rollout step loop, the store keys.
What is ADDED: generic single-cell arms (wA + one cell) through
add_arm(); a vectorized form of the stored-form bisect; per-cell x_mean
accumulation; MODE dispatch (static | census | work); per-seed atomic
checkpoints; in-run C0A anchors.
"""
import hashlib
import py_compile

SRC = "l150_run.py"
s = open(SRC).read()
SRC_SHA = hashlib.sha256(s.encode()).hexdigest()
SRC_LINES = s.count("\n")
assert SRC_LINES == 1059, SRC_LINES
NREP = 0


def rep(old, new, count=1):
    global s, NREP
    n = s.count(old)
    assert n == count, (old[:70], "found", n, "want", count)
    s = s.replace(old, new)
    NREP += n


def splice(opener, closer, new):
    """Replace [opener, closer) — both unique — with new."""
    global s, NREP
    assert s.count(opener) == 1, (opener[:60], s.count(opener))
    i = s.index(opener)
    if closer is None:
        j = len(s)
    else:
        assert s.count(closer) == 1, (closer[:60], s.count(closer))
        j = s.index(closer)
        assert j > i
    s = s[:i] + new + s[j:]
    NREP += 1


# ---- T1 docstring ----
rep('"""L150 run: silW batch rebase',
    '"""L175 scan_run.py — GENERATED by l175/build_scan.py from l150_run.py\n'
    '(sha256 ' + SRC_SHA + ').\n'
    'PREREG l175/PREREG.md FIRST. Single-cell scan on the k=24 (cutwA) base +\n'
    'drive-matched twin. MODE env: static | census | work. cwd = banc/.\n'
    'Lineage docstring retained below.\n\n'
    'L150 run: silW batch rebase')
# ---- T2 imports / mode ----
rep("import json\nimport math\nimport os\nimport time\n",
    "import glob\nimport json\nimport math\nimport os\nimport re\nimport sys\n"
    "import time\nimport zipfile\n")
rep("torch.manual_seed(0)\ntorch.set_num_threads(8)\n",
    "torch.manual_seed(0)\n"
    "torch.set_num_threads(int(os.environ.get(\"L175_THREADS\", \"2\")))\n"
    "MODE = os.environ[\"L175_MODE\"]\n"
    "assert MODE in (\"static\", \"census\", \"work\"), MODE\n"
    "WID = int(os.environ.get(\"L175_WID\", \"0\"))\n"
    "NW = int(os.environ.get(\"L175_NW\", \"1\"))\n")
# ---- T3 arms / gains ----
rep('ARMS = ["full", "b65", "cutwA", "cutng25", "silW", "eMotTop5",\n'
    '        "eMotBot5"]\n'
    'GAIN = dict(full=G_NEW, b65=G65, cutwA=None, cutng25=None,\n'
    '            silW=None, eMotTop5=None, eMotBot5=None)  # silW below (graph-id)\n',
    'ARMS = ["cutwA"]  # L175: per-mode / per-seed arm list assigned below\n'
    'GAIN = dict(full=G_NEW, b65=G65, cutwA=None)\n')
# ---- T4 seeds ----
rep('ANCH = [801, 901]                   # bit-identity anchors (excluded from sample)\n'
    'B33 = list(range(3365, 3381))  # fresh (batch lineage in PREREG)\n'
    'SEEDS = ANCH + B33                  # anchors FIRST: early wiring verdict\n'
    'FRESH = B33\n',
    'ANCH_BIT = [801, 901]               # bit-identity anchors (excluded from sample)\n'
    'B39 = list(range(3545, 3561))       # FRESH (key-scanned absent, PREREG)\n'
    'CENSUS_SEEDS = [801, 901, 3561]     # census-only reference seeds\n'
    'SEEDS = (CENSUS_SEEDS if MODE == "census" else ANCH_BIT + B39)\n'
    'FRESH = B39\n')
# ---- T5 log ----
rep('def log(*a):\n    print(*a, flush=True)\n',
    'def log(*a):\n    print(f"[{MODE}{WID} {time.strftime(\'%H:%M:%S\')}]", *a, flush=True)\n')

# ---- T6 GEN block (after the silW alias block; all symbols defined) ----
GEN_BLOCK = open("l175/gen_block.py.txt").read()
rep('N_OF["silW"] = n_cutk["cutwA"]\n',
    'N_OF["silW"] = n_cutk["cutwA"]\n\n' + GEN_BLOCK + "\n")

# ---- T7 generic init: settle_states + rollout ----
rep('              b65=Xo65.clone())\n    I = {}\n',
    '              b65=Xo65.clone())\n'
    '    for _ga in ARMS:\n'
    '        if _ga in GEN:\n'
    '            st[_ga] = gen_init(_ga, X0o, X0n)\n'
    '    I = {}\n')
rep('             b65=Xo65.clone())\n    Iv = {}\n',
    '             b65=Xo65.clone())\n'
    '    for _ga in ARMS:\n'
    '        if _ga in GEN:\n'
    '            X[_ga] = gen_init(_ga, X0o, X0n)\n'
    '    Iv = {}\n')
# ---- T8 generic noise slice: THREE dicts (settle fn, rollout settle,
# rollout WIN — l123 law: 21-space pattern count-pinned 3) ----
rep('                     b65=nz_o)\n',
    '                     b65=nz_o)\n'
    '        for _ga in ARMS:\n'
    '            if _ga in GEN:\n'
    '                noise[_ga] = nzn[GEN[_ga]["pos_in_new"]]\n', count=3)

# ---- T9 bisect section -> vectorized stored-form + mode dispatch ----
BISECT_BLOCK = open("l175/bisect_block.py.txt").read()
splice("# ---------------- bisects (L142: 2 stored-form + 5 fresh) ----------------\n",
       "# ---------------- rollouts ----------------\n", BISECT_BLOCK + "\n")

# ---- T10 rollout header: resume + per-seed arm list ----
rep('store = {}\n'
    'if os.path.exists("l150/raw_partial.npz"):\n'
    '    z = np.load("l148/raw_partial.npz")\n'
    '    store = {k: z[k] for k in z.files}\n'
    'for seed in SEEDS:\n'
    '    if f"mm_full_{seed}" in store:\n',
    'store, XM = {}, {}\n'
    'if os.path.exists(RAW_PATH) and os.path.exists(XM_PATH):\n'
    '    z = np.load(RAW_PATH)\n'
    '    store = {k: z[k] for k in z.files}\n'
    '    z = np.load(XM_PATH)\n'
    '    XM = {k: z[k] for k in z.files}\n'
    'for seed in SEEDS:\n'
    '    ARMS = arms_for(seed)\n'
    '    if f"mm_cutwA_{seed}" in store and f"xmean_cutwA_{seed}" in XM:\n')
# ---- T11 x_mean accumulators ----
rep('    tr = {a: {kk: np.zeros(WIN, np.float32) for kk in POOLS[a]} for a in ARMS}\n',
    '    tr = {a: {kk: np.zeros(WIN, np.float32) for kk in POOLS[a]} for a in ARMS}\n'
    '    xs = {a: torch.zeros(N_OF[a], dtype=torch.float64) for a in ARMS}\n')
rep('        for a in ARMS:\n'
    '            mm[a][k] = X[a][motor[a]].mean()\n',
    '        for a in ARMS:\n'
    '            xs[a] += X[a][:, 0]\n'
    '            mm[a][k] = X[a][motor[a]].mean()\n')
# ---- T12 per-seed atomic checkpoint ----
rep('    np.savez("l150/raw_partial.npz", **store)\n',
    '    for a in ARMS:\n'
    '        _xv = (xs[a] / WIN).numpy()\n'
    '        XM[f"xmean_{a}_{seed}"] = _xv.astype(np.float32)\n'
    '        _lc = LOC_OF(a)[np.array(TRACK)]\n'
    '        store[f"xwin_{a}_{seed}"] = np.where(\n'
    '            _lc >= 0, _xv[np.maximum(_lc, 0)], np.nan).astype(np.float64)\n'
    '    atomic_savez(RAW_PATH, store)\n'
    '    atomic_savez(XM_PATH, XM)\n'
    '    post_seed(seed)\n')
# ---- T13 tail ----
TAIL_BLOCK = open("l175/tail_block.py.txt").read()
splice('log(f"rollouts done {time.time()-t0:.0f}s")\n', None, TAIL_BLOCK)

# ---- residual scan: no l150 OUTPUT path / B33 / dead-arm token survives
# on a CODE line (comment + docstring lines whitelisted by line context) ----
doc_end = s.index('"""', 3) + 3
code = s[doc_end:]
bad = []
for ln in code.split("\n"):
    t = ln.strip()
    if t.startswith("#"):
        continue
    c = ln.split("  #")[0]
    for tok in ('"l150/', "B33", "raw_partial", "l148/"):
        if tok in c:
            bad.append((tok, ln[:90]))
assert not bad, bad
# assembled-output existence asserts (l142 law c)
for need in ("def add_arm(", "def gen_init(", "def bisect_vec(", "def post_seed(",
             "def arms_for(", "def atomic_savez(", "def settle_states(",
             "def build(", "def wb(", "def pools_for("):
    assert s.count(need) == 1, need
open("l175/scan_run.py", "w").write(s)
py_compile.compile("l175/scan_run.py", doraise=True)
print(f"l175/scan_run.py written: {s.count(chr(10))} lines, {NREP} rep sites, "
      f"src sha {SRC_SHA[:12]}")
