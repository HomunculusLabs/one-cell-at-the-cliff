"""L208 build: generate l208_addendum.py = VERBATIM helper slice + my tail.

PREREG l208/PREREG.md. Zero new rollouts. The head is lines 13-63 of
l169b2_verdict.py byte-for-byte (the certified s_arrays/duty_seeds/side_k
helper atom) — sliced as TEXT, never imported (L175: a lab *_verdict.py is
a SCRIPT, importing it rewrites its own artifacts).
"""
import hashlib
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "l169b2_verdict.py"
TAIL = HERE / "l208_add_tail.py"
OUT = HERE / "l208_addendum.py"

src_lines = SRC.read_text().splitlines(keepends=True)
slice_text = "".join(src_lines[12:63])          # lines 13..63 inclusive
assert slice_text in SRC.read_text(), "head is NOT a literal slice (STOP)"
assert slice_text.startswith("WIN, DT = 6000, 0.01\n"), "head first line drift"
assert slice_text.rstrip().endswith(
    "meanL=round(float(L.mean()), 3), meanR=round(float(R.mean()), 3))"), \
    "head last line drift"
h = hashlib.sha256(slice_text.encode()).hexdigest()
print("HEAD sha256", h[:16], "lines", len(slice_text.splitlines()))

FORBIDDEN = ("savez", "json.dump", "open(", "write_text", "os.replace",
             "to_csv", "pickle")
for tok in FORBIDDEN:
    assert tok not in slice_text, ("forbidden token in head slice", tok)
print("forbidden-token audit on head: clean")

preamble = (
    '"""L208 static (GENERATED by l208_build.py — do not hand-edit).\n\n'
    "Head = l169b2_verdict.py lines 13-63 BYTE-FOR-BYTE (sha256 "
    + h[:16] + ").\nTail = l208_add_tail.py. PREREG l208/PREREG.md.\n"
    '"""\n'
    "import json\n"
    "import math\n"
    "import os\n"
    "\n"
    "import numpy as np\n"
    "\n"
    "HEAD_SHA = \"" + h + "\"\n"
    "\n"
)
OUT.write_text(preamble + slice_text + "\n\n" + TAIL.read_text())
print("wrote", OUT, OUT.stat().st_size, "bytes")
