"""l236_build.py — generate l236_static.py from VERBATIM slices of
l219_static.py plus this card's own MID/TAIL blocks.

Layout (every SLICE is byte-for-byte from the parent):

  SLICE P = l219_static.py 1-989      (prefix: data, pools, f4wA, CSR,
                                       CERT-F4/REW/178/NULL/206/MV/LEFT,
                                       the l169c block mask, the certified
                                       left Perron vector U1)
  MID1    = l236_mid1.py              (read-only fingerprints, parents,
                                       homolog gi DERIVED from l207)
  SLICE H = l219_static.py 1231-1282  (gini219/_rank219/spear219/decomp219)
  SLICE R = l219_static.py 1284-1310  (the carrier's real wiring, identity
                                       (I) and (II), o["identity_gates"])
  SLICE T = l219_static.py 1459-1474  (the contribution table / ginis)
  SLICE C = l219_static.py 1476-1493  (the 35-actor cohort loop + helpers)
  MID2    = l236_mid2.py              (CERT-236A, CERT-236B)
  SLICE M = l219_static.py 1537-1545  (MENU)
  SLICE W = l219_static.py 1548-1556  (wm_null)
  TAIL    = l236_tail.py              (CERT-236C/K, the 1,253-cell pass,
                                       BH-FDR, homolog, predictions, write)

The parent's ~370 s per-draw eigendecomposition loop is CUT. PREREG 0k states
what admits the cut; CERT-236A/B/C in the generated script measure it.
"""
import ast
import hashlib
import pathlib

SRC = pathlib.Path("l219_static.py")
TXT = SRC.read_text()
LINES = TXT.splitlines(keepends=True)
assert len(LINES) == 1672, (len(LINES), "parent line count moved (STOP)")
WHOLE = hashlib.sha256(SRC.read_bytes()).hexdigest()

# ---- PIN 1: the parent's OWN generated banner records its TAIL sha, and that
# ---- tail is a literal SUFFIX of the parent -> the parent IS the generated
# ---- script l219_build.py produced (there is no banner stored inside
# ---- l219/static.json: its "banner" key carries L210's, DISCLOSED).
TAIL_SRC = pathlib.Path("l219_tail.py")
TAIL_TXT = TAIL_SRC.read_text()
TAIL_SHA = hashlib.sha256(TAIL_SRC.read_bytes()).hexdigest()
BANNER = "".join(LINES[:10])
assert f"TAIL       = l219_tail.py (sha256 {TAIL_SHA[:16]})" in BANNER, \
    (TAIL_SHA[:16], "banner does not record this tail (STOP)")
assert TXT.endswith(TAIL_TXT), "l219_tail.py is not a literal SUFFIX (STOP)"
assert "PREREG l219/PREREG.md. Writes l219/static.json ONLY." in BANNER
# PIN 2: the banner's inherited chain is the l210 one L219 itself asserted
for _pin in ("CERT-HEAD1 = l151_static.py lines 1-319 VERBATIM",
             "CERT-210M  = l210_tail.py lines 1-326 VERBATIM"):
    assert _pin in BANNER, (_pin, "inherited chain moved (STOP)")

RANGES = dict(P=(1, 989), H=(1231, 1281), R=(1284, 1309), T=(1459, 1474),
              C=(1476, 1501), M=(1536, 1545), W=(1548, 1556))
FIRST_LAST = dict(
    P=('"""GENERATED by l219_build.py — do not edit by hand.', "iters=400)"),
    H=("def gini219(x):", "mean_u=mu, mean_target_u_bare=mq, ident_rel=res)"),
    R=("# ---------------- the REAL wiring: the carrier's 69 out-edges "
       "---------------",
       '"log1p out-mass and is reported for continuity only"))'),
    T=("# ---------------- Q219-2 (leg a): the per-target contribution table "
       "---------", 'f"{sum(t[\'share_of_S\'] for t in TOP10):.4f}")'),
    C=("COH219 = {}",
       "return float(np.mean([COH219[k][key] < val for k in _fam]))"),
    M=("# ---------------- Q219-3 (leg b): the WEIGHT-MATCHED semi-analytic "
       "nulls ---", 'f"({np.unique(MENU).size:,} distinct cells)")'),
    W=("def wm_null(targets_pool, n_draws, seed):",
       "return dict(S=S, Q=Qd, align=Ad)"))

SLICES, SHAS = {}, {}
for k, (a, b) in RANGES.items():
    s = "".join(LINES[a - 1:b])
    assert s in TXT, (k, "slice is not a literal substring (STOP)")
    SLICES[k] = s
    SHAS[k] = hashlib.sha256(s.encode()).hexdigest()
    fl, ll = FIRST_LAST[k]
    assert s.splitlines()[0].strip() == fl.strip(), \
        (k, "first line", s.splitlines()[0])
    assert s.splitlines()[-1].strip() == ll.strip(), \
        (k, "last line", s.splitlines()[-1])
assert TXT.startswith(SLICES["P"]), "SLICE P is not a literal PREFIX (STOP)"

# ---- line-set audit: the slices are DISJOINT and ordered, and the CUT lines
# ---- are asserted (STRUCTURALLY, by AST) to own the parent's own loops and
# ---- its writer.
_used = set()
_prev = 0
for k in ("P", "H", "R", "T", "C", "M", "W"):
    a, b = RANGES[k]
    assert a > _prev, (k, "slices out of order or overlapping (STOP)")
    _prev = b
    _used |= set(range(a, b + 1))
CUT = sorted(set(range(1, 1673)) - _used)
CUT_TXT = "".join(LINES[i - 1] for i in CUT)
assert len(CUT) == 1672 - len(_used)

# the cut region must own the parent's per-draw loop and its writer
_cuttree = ast.parse("if True:\n" + "".join("    " + LINES[i - 1]
                                            for i in CUT
                                            if LINES[i - 1].strip()
                                            and not LINES[i - 1]
                                            .startswith(("#",))),
                     mode="exec") if False else None
for _tok in ('json.dump(o, _f, indent=1, default=float)',
             'o["predictions"] = dict(',
             'o["Q219_2_table"] = dict(',
             'o["Q219_3_weight_matched"] = dict(',
             'WM = wm_null(MENU, 2000, 21901)'):
    assert _tok in CUT_TXT, (_tok, "cut region does not own it (STOP)")

# the KEPT slices must contain no write site at all (AST, not tokens)
KEPT = "".join(SLICES[k] for k in ("P", "H", "R", "T", "C", "M", "W"))
_tree = ast.parse(KEPT)
_w = []
for n in ast.walk(_tree):
    if isinstance(n, ast.Call):
        f = n.func
        nm = f.attr if isinstance(f, ast.Attribute) else getattr(f, "id", "")
        if nm in ("dump", "dumps_to", "savez", "savez_compressed", "save",
                  "to_csv", "write_text", "write_bytes", "makedirs", "mkdir"):
            _w.append(nm)
assert _w == [], (_w, "a kept slice is not write-free (STOP)")

MID1 = pathlib.Path("l236_mid1.py").read_text()
MID2 = pathlib.Path("l236_mid2.py").read_text()
TAIL = pathlib.Path("l236_tail.py").read_text()
BANNER_OUT = (
    '"""GENERATED by l236_build.py — do not edit by hand.\n'
    f"PARENT     = l219_static.py (whole-file sha256 {WHOLE[:16]}; its own "
    f"banner records TAIL = l219_tail.py sha256 {TAIL_SHA[:16]}, which is a\n"
    "             literal SUFFIX of it).\n"
    + "".join(f"SLICE {k}    = l219_static.py lines {RANGES[k][0]}-"
              f"{RANGES[k][1]} VERBATIM (sha256 {SHAS[k][:16]}).\n"
              for k in ("P", "H", "R", "T", "C", "M", "W"))
    + f"MID1       = l236_mid1.py (sha256 "
      f"{hashlib.sha256(MID1.encode()).hexdigest()[:16]}).\n"
      f"MID2       = l236_mid2.py (sha256 "
      f"{hashlib.sha256(MID2.encode()).hexdigest()[:16]}).\n"
      f"TAIL       = l236_tail.py (sha256 "
      f"{hashlib.sha256(TAIL.encode()).hexdigest()[:16]}).\n"
      'PREREG l236/PREREG.md. Writes l236/static.json ONLY.\n"""\n')

GEN = (BANNER_OUT + SLICES["P"] + MID1 + SLICES["H"] + SLICES["R"]
       + SLICES["T"] + SLICES["C"] + MID2 + SLICES["M"] + SLICES["W"] + TAIL)

# ---- AST audit of the GENERATED file: exactly ONE write, and it is ours
_g = ast.parse(GEN)
_sites = []
for n in ast.walk(_g):
    if isinstance(n, ast.Call):
        f = n.func
        nm = f.attr if isinstance(f, ast.Attribute) else getattr(f, "id", "")
        if nm in ("dump", "savez", "savez_compressed", "to_csv",
                  "write_text", "write_bytes"):
            _sites.append(nm)
        if nm == "makedirs":
            _sites.append("makedirs")
assert _sites.count("dump") == 1, (_sites, "not exactly one json.dump (STOP)")
assert _sites.count("makedirs") == 1, (_sites, "makedirs count (STOP)")
assert 'json.dump(o, _f, indent=1, default=float)' in TAIL
# no lab module imported (L175)
for n in ast.walk(_g):
    if isinstance(n, (ast.Import, ast.ImportFrom)):
        mods = ([a.name for a in n.names] if isinstance(n, ast.Import)
                else [n.module or ""])
        for m in mods:
            assert not (m.startswith("l1") or m.startswith("l2")), \
                (m, "a lab module is imported (STOP)")

OUT = pathlib.Path("l236_static.py")
OUT.write_text(GEN)
gsha = hashlib.sha256(OUT.read_bytes()).hexdigest()
print(f"[build] parent l219_static.py whole {WHOLE[:16]} tail {TAIL_SHA[:16]}")
for k in ("P", "H", "R", "T", "C", "M", "W"):
    print(f"[build] SLICE {k} {RANGES[k][0]}-{RANGES[k][1]} "
          f"({RANGES[k][1]-RANGES[k][0]+1} lines) sha {SHAS[k][:16]}")
print(f"[build] kept {len(_used)} parent lines, CUT {len(CUT)} "
      f"(cut owns the per-draw loop, Q219_2/Q219_3 writers and json.dump)")
print(f"[build] wrote l236_static.py {len(GEN.splitlines())} lines "
      f"sha {gsha[:16]}")
