"""l178_build.py — generate l178_static.py = l151_static.py lines 1-319
VERBATIM (head) + l178_tail.py (tail). CERT-HEAD: the head slice is asserted
byte-for-byte against l151_static.py and its sha256 recorded, and the head is
asserted to contain NO file write (so running it produces no side effects on
l151's own artifacts — the L175 lesson: a lab run script is a SCRIPT, never a
library, and must never be imported).
"""
import hashlib
import pathlib

HEAD_SRC = pathlib.Path("l151_static.py")
TAIL_SRC = pathlib.Path("l178_tail.py")
OUT = pathlib.Path("l178_static.py")
N_HEAD = 319

head_lines = HEAD_SRC.read_text().splitlines(keepends=True)
assert len(head_lines) >= N_HEAD, (len(head_lines), "l151_static.py too short")
head = "".join(head_lines[:N_HEAD])
# byte-for-byte: the slice must be a literal prefix of the source file
assert HEAD_SRC.read_text().startswith(head), "head slice is not a prefix"
# no file writes, no imports of lab scripts inside the head
for bad in ("\"w\"", "'w'", "import l1", "import l9", "savez", "to_csv"):
    assert bad not in head, f"head contains forbidden token {bad!r}"
head_sha = hashlib.sha256(head.encode()).hexdigest()
tail = TAIL_SRC.read_text()
tail_sha = hashlib.sha256(tail.encode()).hexdigest()

banner = (
    '"""GENERATED by l178_build.py — do not edit by hand.\n'
    f"Head = l151_static.py lines 1-{N_HEAD} VERBATIM "
    f"(sha256 {head_sha[:16]}).\n"
    f"Tail = l178_tail.py (sha256 {tail_sha[:16]}).\n"
    'PREREG l178/PREREG.md. Writes l178/static.json ONLY.\n'
    '"""\n')
OUT.write_text(banner + head + tail)
written = OUT.read_text()
assert head in written and tail in written, "generated file lost a slice"
# diff audit: the generated body MINUS the banner must be exactly head+tail
assert written == banner + head + tail
print(f"wrote {OUT} ({len(written.splitlines())} lines)")
print(f"head sha256 {head_sha}")
print(f"tail sha256 {tail_sha}")
