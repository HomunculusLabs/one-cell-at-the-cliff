"""L198 builder: count-asserted ADDITIVE transform of the certified L187
harness banc/l187/relay_run.py -> banc/l198/twin_run.py. Run from banc/.
VERBATIM from l187/relay_run.py: extraction, ladder, build()/wb()/pools_for(),
add_arm()/gen_init(), the whole L187 arms block (sc25 / rcut graphs, aliases,
CERT-GEN / CERT-MULTI / CERT-SUB), settle_states, bisect_vec, the rollout
step loop, store keys, per-seed atomic checkpoints.
REPLACED: env names, seed list, output dir, the static dump (-> twin block:
stored-census selection + six twin graphs), gains + anchors block, tail."""
import hashlib
import py_compile

SRC = "l187/relay_run.py"
s = open(SRC).read()
SRC_SHA = hashlib.sha256(s.encode()).hexdigest()
assert SRC_SHA == "b7c486bf32505e95b57405db719c5ebe1389c3f3e65e925f4119791451b94327", SRC_SHA
assert s.count("\n") == 1765
NREP = 0


def rep(old, new, count=1):
    global s, NREP
    n = s.count(old)
    assert n == count, (old[:70], "found", n, "want", count)
    s = s.replace(old, new)
    NREP += n


def splice(opener, closer, new):
    global s, NREP
    assert s.count(opener) == 1, (opener[:60], s.count(opener))
    i = s.index(opener)
    if closer is None:
        j = len(s)
    else:
        assert s.count(closer) == 1, (closer[:60], s.count(closer))
        j = s.index(closer)
        assert j > i
    s = s[:i] + new + s[j:]
    NREP += 1


rep('"""L187 relay_run.py — GENERATED by l187/build_relay.py from l175/scan_run.py\n',
    '"""L198 twin_run.py — GENERATED by l198/build_twin.py from l187/relay_run.py\n'
    '(sha256 ' + SRC_SHA + ').\n'
    'PREREG l198/PREREG.md FIRST. Relay-matched cord-interneuron twin (+ 5\n'
    'registered runners-up), same-batch relay-cut and carrier-cut references,\n'
    'on the k=24 (cutwA) base. MODE env: static | work. cwd = banc/.\n'
    'L187 docstring retained below.\n\n'
    'L187 relay_run.py — GENERATED by l187/build_relay.py from l175/scan_run.py\n')
rep('torch.set_num_threads(int(os.environ.get("L187_THREADS", "2")))\n'
    'MODE = os.environ["L187_MODE"]\n'
    'assert MODE in ("static", "work"), MODE\n'
    'WID = int(os.environ.get("L187_WID", "0"))\n'
    'NW = int(os.environ.get("L187_NW", "6"))\n',
    'torch.set_num_threads(int(os.environ.get("L198_THREADS", "2")))\n'
    'MODE = os.environ["L198_MODE"]\n'
    'assert MODE in ("static", "work"), MODE\n'
    'WID = int(os.environ.get("L198_WID", "0"))\n'
    'NW = int(os.environ.get("L198_NW", "6"))\n')
rep('B41 = list(range(3609, 3625))       # FRESH (key-scanned absent, PREREG l187)\n'
    'SEEDS = ANCH_BIT + ANCH_175 + B41   # anchors FIRST\n'
    'FRESH = B41\n'
    'assert not (set(B41) & (set(B39) | set(B40))) and ANCH_175[0] in B39\n',
    'B41 = list(range(3609, 3625))       # L187 batch: STORED, never re-sampled\n'
    'B42 = list(range(3641, 3657))       # L190 batch: STORED, never re-sampled\n'
    'ANCH_187 = [3609]                   # L187-reproduction bit anchor (not in sample)\n'
    'B43 = list(range(3673, 3689))       # FRESH (key-scanned absent, PREREG l198)\n'
    'SEEDS = ANCH_BIT + ANCH_175 + ANCH_187 + B43   # anchors FIRST\n'
    'FRESH = B43\n'
    'assert not (set(B43) & (set(B39) | set(B40) | set(B41) | set(B42)))\n'
    'assert ANCH_175[0] in B39 and ANCH_187[0] in B41\n')
rep('OUT = "l187"\n', 'OUT = "l198"\n')
rep('_fresh = set(B41)\n', '_fresh = set(B43)\n')
rep('    if _f.startswith("../banc/l187/"):\n        continue\n',
    '    if _f.startswith("../banc/l198/"):\n        continue\n')
TWIN_BLOCK = open("l198/twin_block.py.txt").read()
splice('if MODE == "static":\n    atomic_json(f"{OUT}/static.json", dict(\n        design="L187 static pins',
       '# ===================== end L175 GEN BLOCK =====================\n', TWIN_BLOCK)
GAINS_BLOCK = open("l198/gains_block.py.txt").read()
splice('assert ANCH == [11, 22, 33]\n',
       '# ---------------- rollouts ----------------\n', GAINS_BLOCK)
TAIL_BLOCK = open("l198/tail_block.py.txt").read()
splice('log(f"rollouts done {time.time()-t0:.0f}s")\n', None, TAIL_BLOCK)

doc_end = s.index('"""', 3) + 3
code = s[doc_end:]
bad = []
for ln in code.split("\n"):
    if ln.strip().startswith("#"):
        continue
    c = ln.split("  #")[0]
    for tok in ("L187_", 'OUT = "l187"', "set(B41)\n"):
        if tok in c:
            bad.append((tok, ln[:90]))
    if "l187/" in c or "l190/" in c or "l185/" in c or "l175/" in c:
        assert ("json.load(open(" in c) or ("np.load(" in c) or ("startswith" in c) \
            or ("pd.read_csv(" in c), ("non-read", ln)
assert not bad, bad
assert s.count('OUT = "l198"\n') == 1
for keep in (
        "            drive = torch.sparse.mm(WB[a], X[a]) * GAIN[a] + Iv[a]\n"
        "            if sin_t > 0:\n"
        "                drive[mech[a], 0] = drive[mech[a], 0] + sin_t\n"
        "            t = torch.relu(drive + BG)\n"
        "            t = (t + noise[a]).clamp(max=RMAX)\n"
        "            X[a] = X[a] + (DT / TAU) * (t - X[a])\n"
        "            if a in CLAMP:\n"
        "                X[a][CLAMP[a], 0] = 0.0\n",
        "    atomic_savez(RAW_PATH, store)\n    atomic_savez(XM_PATH, XM)\n"
        "    post_seed(seed)\n"):
    assert s.count(keep) == 1, keep[:50]
for need in ("def add_arm(", "def gen_init(", "def bisect_vec(", "def post_seed(",
             "def arms_for(", "def settle_states(", "def select_twin("):
    assert s.count(need) == 1, need
open("l198/twin_run.py", "w").write(s)
py_compile.compile("l198/twin_run.py", doraise=True)
print(f"l198/twin_run.py written: {s.count(chr(10))} lines, {NREP} rep sites, src sha {SRC_SHA[:12]}")
