"""L214 build: generate l214_static.py from VERBATIM source slices + my tail.

PREREG l214/PREREG.md. Zero new rollouts.

Slice 1 = l169b2_verdict.py lines 13-63 byte-for-byte (the certified
  s_arrays/duty_seeds/side_k helper atom; sha asserted against the value
  l208_build_add.py recorded and l208/static.json stored).
Slice 2 = l208_add_tail.py lines 55-72 byte-for-byte (flo_side + spearman —
  the floor currency itself, so it is bit-identical to the post-hoc leg
  rather than re-implemented).

Neither is imported (L175: a lab *_verdict.py / run script is a SCRIPT;
importing it re-executes it and rewrites its own artifacts).
"""
import hashlib
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
SRC1 = HERE / "l169b2_verdict.py"
SRC2 = HERE / "l208_add_tail.py"
TAIL = HERE / "l214_tail.py"
OUT = HERE / "l214_static.py"

HEAD_SHA_EXPECTED = (
    "de636f4a18ee789b8bd51fca5f7823ea6302ffd58be630b50c70965e865b8e0c")

t1 = SRC1.read_text()
s1 = "".join(t1.splitlines(keepends=True)[12:63])          # lines 13..63
assert s1 in t1, "slice 1 is NOT a literal slice (STOP)"
assert s1.startswith("WIN, DT = 6000, 0.01\n"), "slice 1 first line drift"
assert s1.rstrip().endswith(
    "meanL=round(float(L.mean()), 3), meanR=round(float(R.mean()), 3))"), \
    "slice 1 last line drift"
h1 = hashlib.sha256(s1.encode()).hexdigest()
assert h1 == HEAD_SHA_EXPECTED, ("slice 1 sha DRIFT vs l208 record", h1)
assert "def duty_seeds" in s1 and "def s_arrays" in s1 and "def side_k" in s1

t2 = SRC2.read_text()
s2 = "".join(t2.splitlines(keepends=True)[54:72])          # lines 55..72
assert s2 in t2, "slice 2 is NOT a literal slice (STOP)"
assert s2.startswith("def flo_side(raw, arm, seed, pk, mask):\n"), \
    "slice 2 first line drift"
assert s2.rstrip().endswith(
    'return float((rx * ry).sum() / den) if den > 0 else float("nan")'), \
    "slice 2 last line drift"
assert "def spearman" in s2, "slice 2 lost spearman"
h2 = hashlib.sha256(s2.encode()).hexdigest()
print("SLICE1 sha256", h1[:16], "lines", len(s1.splitlines()))
print("SLICE2 sha256", h2[:16], "lines", len(s2.splitlines()))

FORBIDDEN = ("savez", "json.dump", "write_text", "os.replace", "to_csv",
             "pickle", "open(")
for nm, sl in (("slice1", s1), ("slice2", s2)):
    for tok in FORBIDDEN:
        assert tok not in sl, ("forbidden token in " + nm, tok)
print("forbidden-token audit on both slices: clean")

tail = TAIL.read_text()
for tok in ("import l208", "import l169b2", "import l175f", "from l2"):
    assert tok not in tail, ("tail imports a lab module (L175)", tok)
assert 'json.dump' in tail and 'l214/static.json' in tail, "tail writes?"
assert "addendum_floor.json" in tail and "l208/static.json" in tail, \
    "tail must read both prior artifacts for the reproduction gates"

preamble = (
    '"""L214 static (GENERATED by l214_build.py — do not hand-edit).\n\n'
    "Slice 1 = l169b2_verdict.py lines 13-63 BYTE-FOR-BYTE (sha256 "
    + h1[:16] + ").\nSlice 2 = l208_add_tail.py lines 55-72 BYTE-FOR-BYTE "
    "(sha256 " + h2[:16] + ").\nTail = l214_tail.py. PREREG l214/PREREG.md.\n"
    '"""\n'
    "import json\n"
    "import math\n"
    "import os\n"
    "\n"
    "import numpy as np\n"
    "\n"
    'HEAD_SHA = "' + h1 + '"\n'
    'SLICE2_SHA = "' + h2 + '"\n'
    "\n"
)
OUT.write_text(preamble + s1 + "\n\n" + s2 + "\n\n" + tail)
gen = hashlib.sha256(OUT.read_bytes()).hexdigest()
print("wrote", OUT, OUT.stat().st_size, "bytes; generated sha", gen[:16])
