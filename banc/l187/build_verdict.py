"""L187 verdict builder: slice the certified helper block of l150_verdict.py
VERBATIM (S_of / s_arrays / duty_seeds / side_k / wilson + constants; the
SAME slice + sha L175 and L185 used) and append l187/verdict_tail.py.txt. Run from
banc/."""
import hashlib
import os
import py_compile

src = open("l150_verdict.py").read()
opener = "# ---- batches ----\n"
assert src.count(opener) == 1
head = src[:src.index(opener)]
assert head.count("\n") == 71, head.count("\n")
for need in ("def S_of(", "def s_arrays(", "def duty_seeds(", "def side_k(",
             "def wilson(", "MEAS0 = 500", "TS = np.arange(499, WIN, 10)",
             "SEGB = [(0, 2000, 0.7), (2000, 4000, 1.4), (4000, 6000, 0.7)]"):
    assert head.count(need) == 1, need
sha = hashlib.sha256(head.encode()).hexdigest()
assert sha[:16] == "5c8323f2755f1d0c", sha      # == the L175 verdict's helper sha
# and the L175 verdict really carries this exact block
v175 = open("l175/verdict_l175.py").read()
assert head in v175, "helper block != the one inside l175/verdict_l175.py"
out = (f"# GENERATED by l187/build_verdict.py — helper block == l150_verdict.py"
       f" lines 1-71 VERBATIM (sha256 {sha[:16]})\n" + head
       + open("l187/verdict_tail.py.txt").read())
for need in ("def S_of(", "def duty_seeds(", "def side_k(", "def wilson(",
             "def classify(", "def arm_row("):
    assert out.count(need) == 1, need
open("l187/verdict_l187.py.new", "w").write(out)
py_compile.compile("l187/verdict_l187.py.new", doraise=True)
os.replace("l187/verdict_l187.py.new", "l187/verdict_l187.py")
print("l187/verdict_l187.py written, helper sha", sha[:16])
