"""l230_build.py — generate l230_static.py from VERBATIM certified slices.

SLICE A = l216_static.py lines 1-1360: a literal PREFIX of the parent, cut
          immediately BEFORE its writer (os.makedirs/json.dump at 1361-1362)
          and AST-verified to contain ZERO write sites. Re-runs every pin and
          CERT-F4/178/GEN/205/GAP/209 plus the NO-OP as the code that
          actually produced l216/static.json, and leaves TABLE / NULLS /
          AINF / PERRON / GAPS / FITS / CELLS in memory.
SLICE B = l217_tail.py lines 245-258: L217's `dcross` function verbatim, so
          the measured crossing is produced by the expression that wrote
          l217/static.json.
TAIL    = l230_tail.py.

Writes l230_static.py ONLY. Run from ~/critters/peabrain-lab/banc.
"""
import ast
import hashlib
import os
import sys

SRC_A, LO_A, HI_A = "l216_static.py", 1, 1360
SRC_B, LO_B, HI_B = "l217_tail.py", 245, 258
TAIL = "l230_tail.py"
OUT = "l230_static.py"
PARENT_TAIL = "l216_tail.py"
PARENT_TAIL_SHA16 = "d9cb45022621452b"   # recorded in l216_static.py's banner


def sha(t):
    return hashlib.sha256(t.encode()).hexdigest()


def read(p):
    with open(p) as f:
        return f.read()


A_full, B_full, T_full = read(SRC_A), read(SRC_B), read(TAIL)
PT_full = read(PARENT_TAIL)

A_lines, B_lines = A_full.split("\n"), B_full.split("\n")
sliceA = "\n".join(A_lines[LO_A - 1:HI_A]) + "\n"
sliceB = "\n".join(B_lines[LO_B - 1:HI_B]) + "\n"

# ---- 1. the slices are literal text of their sources ----------------------
assert A_full.startswith(sliceA), "SLICE A is not a literal PREFIX of the parent"
assert sliceB in B_full, "SLICE B is not a literal substring of l217_tail.py"
print(f"[slice] A = {SRC_A} {LO_A}-{HI_A} ({len(sliceA)} B) sha {sha(sliceA)[:16]}")
print(f"[slice] B = {SRC_B} {LO_B}-{HI_B} ({len(sliceB)} B) sha {sha(sliceB)[:16]}")
print(f"[pin]   {SRC_A} whole sha {sha(A_full)[:16]}")
print(f"[pin]   {SRC_B} whole sha {sha(B_full)[:16]}")

# ---- 2. PARENT PIN: l216_tail.py is a literal SUFFIX of l216_static.py ----
# and its sha is exactly what that file's own generated banner records. This
# is what proves SLICE A is the code that produced l216/static.json.
assert A_full.endswith(PT_full), f"{PARENT_TAIL} is not a SUFFIX of {SRC_A}"
assert sha(PT_full)[:16] == PARENT_TAIL_SHA16, \
    (sha(PT_full)[:16], PARENT_TAIL_SHA16, "parent tail sha drift")
assert f"TAIL       = {PARENT_TAIL} (sha256 {PARENT_TAIL_SHA16})" in A_lines[11], \
    ("banner line 12", A_lines[11])
print(f"[PARENT PIN] {PARENT_TAIL} sha {PARENT_TAIL_SHA16} is a literal SUFFIX "
      f"of {SRC_A} AND the value that file's own banner records — GREEN")

# ---- 3. STRUCTURAL cut audit: the 6 CUT lines own the parent's writer -----
cutA = A_lines[HI_A:]
cut_txt = "\n".join(cutA)
for tok in ('os.makedirs("l216"', 'json.dump(o, open("l216/static.json"',
            "L216 DONE"):
    assert tok in cut_txt, (tok, "expected in the CUT region")
    assert tok not in sliceA, (tok, "leaked into SLICE A")
# STRUCTURAL, not a count: every top-level statement of the cut region must
# be a bare call to makedirs / json.dump / log — so the cut carries the
# writer and the closing log line and NOTHING that SLICE A could need. (A
# hand-typed line count of 5 halted the first build at the true 6: the
# derive-never-retype law, this time on a COUNT.)
_ct = ast.parse(cut_txt)
_cut_calls = []
for _n in _ct.body:
    assert isinstance(_n, ast.Expr) and isinstance(_n.value, ast.Call), \
        (ast.unparse(_n)[:60], "CUT region carries a non-call statement")
    _f = _n.value.func
    _cut_calls.append(_f.attr if isinstance(_f, ast.Attribute) else _f.id)
assert sorted(_cut_calls) == ["dump", "log", "log", "makedirs"], \
    (_cut_calls, "unexpected CUT content")
print(f"[cut] {len(cutA)} cut lines / {len(_ct.body)} statements "
      f"{_cut_calls} — AST-proven to be the parent's writer plus its closing "
      f"log; SLICE A holds none of it")

# ---- 4. SLICE B carries dcross and nothing else ---------------------------
assert sliceB.lstrip().startswith("# ---------------- Q2: d_cross"), sliceB[:80]
assert "def dcross(series):" in sliceB, "SLICE B lost dcross"
_bt = ast.parse(sliceB)
_bdefs = [n.name for n in _bt.body if isinstance(n, ast.FunctionDef)]
assert _bdefs == ["dcross"], (_bdefs, "SLICE B defines more than dcross")
assert not [n for n in _bt.body if not isinstance(n, ast.FunctionDef)], \
    "SLICE B carries statements outside the function"
print(f"[slice B] AST: defines exactly {_bdefs} and nothing else")

# ---- 5. assemble ----------------------------------------------------------
banner = (
    '"""GENERATED by l230_build.py — do not edit by hand.\n'
    f"SLICE A = {SRC_A} lines {LO_A}-{HI_A} VERBATIM, a literal PREFIX cut\n"
    f"          immediately before the parent's writer (sha256 "
    f"{sha(sliceA)[:16]}; whole-file sha256 {sha(A_full)[:16]}).\n"
    f"          AST-verified: ZERO write sites. Inherits every pin plus\n"
    f"          CERT-F4 / CERT-178 / CERT-GEN / CERT-205 / CERT-GAP /\n"
    f"          CERT-209 and the lam1 NO-OP as the code that produced\n"
    f"          l216/static.json.\n"
    f"PARENT PIN: {PARENT_TAIL} (sha256 {PARENT_TAIL_SHA16}) is a literal\n"
    f"          SUFFIX of {SRC_A} and the sha that file's banner records.\n"
    f"SLICE B = {SRC_B} lines {LO_B}-{HI_B} VERBATIM — L217's dcross\n"
    f"          (sha256 {sha(sliceB)[:16]}; whole-file sha256 "
    f"{sha(B_full)[:16]}).\n"
    f"TAIL    = {TAIL} (sha256 {sha(T_full)[:16]}).\n"
    "PREREG l230/PREREG.md. Writes l230/static.json ONLY.\n"
    '"""\n')
out = banner + sliceA + "\n" + sliceB + "\n" + T_full

# ---- 6. AST audits on the GENERATED file ---------------------------------
tree = ast.parse(out)

# (a) no lab module imported (L175: importing a lab script RE-RUNS it)
bad = []
for n in ast.walk(tree):
    if isinstance(n, ast.Import):
        bad += [a.name for a in n.names]
    elif isinstance(n, ast.ImportFrom):
        bad.append(n.module or "")
mods = sorted(set(m.split(".")[0] for m in bad))
lab = [m for m in mods if m.startswith("l") and len(m) > 1 and m[1].isdigit()]
assert not lab, (lab, "a lab module is imported (L175)")
print(f"[AST import] modules {mods} — no lab module imported")

# (b) write-SITE audit: exactly one write, and it targets l230/static.json.
# Gated on the SITE (an open(...,'w') call or a dump/savez), never on a bare
# token: a bare-token audit fires on prose (the tick 226/248/251/256/258 trap).
WRITE_FUNCS = {"savez", "savez_compressed", "write_text", "to_csv",
               "replace", "rename", "savefig", "save"}
writes, makedirs = [], []
for n in ast.walk(tree):
    if not isinstance(n, ast.Call):
        continue
    fn = n.func
    name = fn.attr if isinstance(fn, ast.Attribute) else (
        fn.id if isinstance(fn, ast.Name) else "")
    if name == "open":
        mode = ""
        if len(n.args) > 1 and isinstance(n.args[1], ast.Constant):
            mode = str(n.args[1].value)
        for kw in n.keywords:
            if kw.arg == "mode" and isinstance(kw.value, ast.Constant):
                mode = str(kw.value.value)
        if any(c in mode for c in "wax+"):
            writes.append((n.lineno, "open:" + mode,
                           ast.unparse(n.args[0]) if n.args else "?"))
    elif name == "dump" and isinstance(fn, ast.Attribute) \
            and isinstance(fn.value, ast.Name) and fn.value.id == "json":
        tgt = ast.unparse(n.args[1]) if len(n.args) > 1 else "?"
        writes.append((n.lineno, "json.dump", tgt))
    elif name in WRITE_FUNCS and isinstance(fn, ast.Attribute):
        mod = fn.value.id if isinstance(fn.value, ast.Name) else ""
        if mod in ("np", "os", "torch", "plt"):
            writes.append((n.lineno, f"{mod}.{name}",
                           ast.unparse(n.args[0]) if n.args else "?"))
    elif name == "makedirs":
        makedirs.append((n.lineno, ast.unparse(n.args[0]) if n.args else "?"))

opens = [w for w in writes if w[1].startswith("open:")]
dumps = [w for w in writes if w[1] == "json.dump"]
others = [w for w in writes if w not in opens and w not in dumps]
assert not others, (others, "unexpected write-like call")
assert len(opens) == 1 and len(dumps) == 1, (opens, dumps, "write count")
assert opens[0][0] == dumps[0][0], (opens, dumps,
                                    "the open and the dump are not the same "
                                    "statement")
assert "'l230/static.json'" in opens[0][2].replace('"', "'"), opens[0]
assert len(makedirs) == 1 and "l230" in makedirs[0][1], makedirs
print(f"[AST write] exactly ONE write site: line {opens[0][0]} "
      f"json.dump(..., open({opens[0][2]}, 'w')) + one makedirs {makedirs[0][1]}")

# (c) SLICE A alone must hold ZERO write sites — proven on its own AST
treeA = ast.parse(sliceA)
wA, mA = 0, 0
for n in ast.walk(treeA):
    if not isinstance(n, ast.Call):
        continue
    fn = n.func
    name = fn.attr if isinstance(fn, ast.Attribute) else (
        fn.id if isinstance(fn, ast.Name) else "")
    if name == "open":
        mode = ""
        if len(n.args) > 1 and isinstance(n.args[1], ast.Constant):
            mode = str(n.args[1].value)
        for kw in n.keywords:
            if kw.arg == "mode" and isinstance(kw.value, ast.Constant):
                mode = str(kw.value.value)
        if any(c in mode for c in "wax+"):
            wA += 1
    if name == "dump" and isinstance(fn, ast.Attribute) \
            and isinstance(fn.value, ast.Name) and fn.value.id == "json":
        wA += 1
    if name in WRITE_FUNCS and isinstance(fn, ast.Attribute) \
            and isinstance(fn.value, ast.Name) and fn.value.id in ("np", "os",
                                                                   "torch"):
        wA += 1
    if name == "makedirs":
        mA += 1
assert wA == 0 and mA == 0, (wA, mA, "SLICE A is NOT write-free")
print("[AST write] SLICE A proven WRITE-FREE (0 write sites, 0 makedirs) — "
      "re-running the parent cannot touch l216/static.json")

# (d) the tail must read the objects it claims to inherit
for nm in ("TABLE", "NULLS", "AINF", "PERRON", "GAPS", "FITS", "CELLS",
           "side_stats_from", "decorate", "dcross", "LOCAL", "SUBS",
           "JOINTS", "NDRAW", "DMAX", "MAXREL"):
    assert nm in T_full, (nm, "tail does not use an inherited object")
    assert nm in (sliceA + sliceB), (nm, "inherited object not defined in a slice")
print("[deps] all 16 inherited objects are defined in the slices and used by "
      "the tail")

# (e) the tail must not redefine the parent's writer target
assert "l216/static.json" in T_full, "tail should READ l216/static.json"
assert 'open("l216/static.json", "w")' not in T_full, "tail writes the parent!"

with open(OUT, "w") as f:
    f.write(out)
print(f"[write] {OUT} {len(out.splitlines())} lines sha {sha(out)[:16]}")
print(f"[write] tail sha {sha(T_full)[:16]}")
sys.exit(0)
