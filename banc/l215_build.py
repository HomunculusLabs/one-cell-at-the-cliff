"""l215_build.py — generate l215_static.py from certified verbatim slices.

l215_static.py = banner
               + HEAD1 : l151_static.py lines 1-319      (BYTE-FOR-BYTE)
               + PRE   : the output dict `o` that HEAD2 writes into
               + HEAD2 : l178_tail.py lines 22-83         (BYTE-FOR-BYTE)
               + TAIL  : l215_tail.py

Both head slices are the SAME slices L205 used; their sha256 are asserted
against the values l205_static.py's banner recorded, so a moved/edited source
HALTS the build (L210/L211/L212/L213 inherited-sha discipline). No lab module
is imported (L175: a lab run script is a SCRIPT, importing it rewrites its own
artifacts). PREREG l215/PREREG.md.
"""
import hashlib
import pathlib

H1_SRC = pathlib.Path("l151_static.py")
H2_SRC = pathlib.Path("l178_tail.py")
TAIL_SRC = pathlib.Path("l215_tail.py")
OUT = pathlib.Path("l215_static.py")
N_H1 = 319
H2_LO, H2_HI = 22, 83          # 1-indexed inclusive

# sha256[:16] as RECORDED BY L205's generated banner — inherited pins
INHERIT = {"head1": "e6245e8306dc8a0f", "head2": "66112b0c221d02d8"}

h1_text = H1_SRC.read_text()
h1_lines = h1_text.splitlines(keepends=True)
assert len(h1_lines) >= N_H1, (len(h1_lines), "l151_static.py too short")
head1 = "".join(h1_lines[:N_H1])
assert h1_text.startswith(head1), "HEAD1 slice is not a literal prefix"

h2_text = H2_SRC.read_text()
h2_lines = h2_text.splitlines(keepends=True)
assert len(h2_lines) >= H2_HI, (len(h2_lines), "l178_tail.py too short")
head2 = "".join(h2_lines[H2_LO - 1:H2_HI])
assert head2 in h2_text, "HEAD2 slice is not a literal slice"
assert head2.startswith("FLOOR = 4\n"), head2[:40]
assert head2.rstrip().endswith("del _z"), head2[-60:]

sh = {k: hashlib.sha256(v.encode()).hexdigest()
      for k, v in (("head1", head1), ("head2", head2))}
for k, want in INHERIT.items():
    assert sh[k][:16] == want, (k, sh[k][:16], want, "INHERITED SHA DRIFT (STOP)")
print("inherited sha pins GREEN:", INHERIT)

# NOTE: "pickle" is deliberately NOT in this list — HEAD2 contains
# `np.load(..., allow_pickle=True)`, a READ. The audit targets WRITE tokens
# and lab-module imports (the L175 lesson), which is L205's certified list.
FORBIDDEN = ('"w"', "'w'", "import l1", "import l9", "savez", "to_csv",
             "json.dump", "write_text", "os.replace")
for name, blob in (("HEAD1", head1), ("HEAD2", head2)):
    for bad in FORBIDDEN:
        assert bad not in blob, f"{name} contains forbidden token {bad!r}"
print("forbidden-token audit on both heads: clean")

PRE = (
    "\n# ---- L215 PRE (the only hand-written lines between the two certified"
    " slices):\n"
    "# HEAD2 writes o['cert_f4'] and o['gains'], so the dict must exist first.\n"
    "o = {\"design\": \"L215 dead-left-trochanter resurrection (static): \"\n"
    "     \"sign-decomposed per-side in-mass into the Ti/Tr pools on cutwA vs \"\n"
    "     \"f4wA, with the sub-floor REMOVED mass split by sign, against a \"\n"
    "     \"sign-neutral counterfactual. Zero rollouts, zero dynamics.\",\n"
    "     \"prereg\": \"l215/PREREG.md\"}\n\n")

tail = TAIL_SRC.read_text()
sh["tail"] = hashlib.sha256(tail.encode()).hexdigest()

# the tail must not re-transcribe certified machinery
for bad in ("def mass(", "pm4 = w_syn", "keep_f4 = keep_new"):
    assert bad not in tail, ("TAIL re-transcribes certified machinery", bad)

banner = (
    '"""GENERATED by l215_build.py — do not edit by hand.\n'
    f"HEAD1 = l151_static.py lines 1-{N_H1} VERBATIM (sha256 {sh['head1'][:16]}).\n"
    f"HEAD2 = l178_tail.py lines {H2_LO}-{H2_HI} VERBATIM "
    f"(sha256 {sh['head2'][:16]}).\n"
    f"TAIL  = l215_tail.py (sha256 {sh['tail'][:16]}).\n"
    'PREREG l215/PREREG.md. Writes l215/static.json ONLY.\n'
    '"""\n')

body = banner + head1 + PRE + head2 + tail
OUT.write_text(body)
written = OUT.read_text()
assert written == body
for name, blob in (("HEAD1", head1), ("HEAD2", head2), ("TAIL", tail)):
    assert blob in written, f"generated file lost {name}"
print(f"wrote {OUT} ({len(written.splitlines())} lines)")
for k, v in sh.items():
    print(f"{k} sha256 {v}")
