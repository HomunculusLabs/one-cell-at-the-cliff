"""l213b_build.py — generate l213_addendum.py: the SAME certified stack as
l213_static.py (heads 1-5 + mid), then l213_tail.py lines 1-221 VERBATIM
(everything up to and including the POPULATION block, which re-runs CERT-207,
CERT-T and the premise asserts as free certification), then the addendum tail.

The l213_tail.py slice is CUT at line 221 so the registered Q1/Q2/Q3 blocks
and the `json.dump` into l213/static.json are NOT included: this script
cannot rewrite the parent card's artifact (L175).
"""
import hashlib
import pathlib

SRCS = [("l151_static.py", 1, 319, "e6245e8306dc8a0f"),
        ("l178_tail.py", 7, 149, "6e2e8fa4bd19eced"),
        ("l206_tail.py", 22, 121, "29a830839ebc7837"),
        ("l207_tail.py", 48, 112, "946dab653fe60b16"),
        ("l207_tail.py", 199, 241, "340c0432c85c6e7b"),
        ("l213_tail.py", 1, 221, None)]
MID_SRC = pathlib.Path("l206_mid.py")
TAIL_SRC = pathlib.Path("l213b_tail.py")
OUT = pathlib.Path("l213_addendum.py")
FORBIDDEN = ("import l1", "import l9", "savez", "to_csv")


def slice_lines(path, a, b):
    txt = pathlib.Path(path).read_text()
    lines = txt.splitlines(keepends=True)
    assert len(lines) >= b, (path, len(lines), b, "source too short")
    s = "".join(lines[a - 1:b])
    assert s in txt, (path, a, b, "slice is not a literal substring")
    if a == 1:
        assert txt.startswith(s), (path, "head slice is not a prefix")
    for bad in FORBIDDEN:
        assert bad not in s, f"{path} [{a},{b}] forbidden {bad!r}"
    return s, hashlib.sha256(s.encode()).hexdigest()


parts, shas = [], []
for p, a, b, want in SRCS:
    s, sha = slice_lines(p, a, b)
    if want is not None:
        assert sha[:16] == want, (p, a, b, sha[:16], want, "SOURCE MOVED (STOP)")
    parts.append(s)
    shas.append((p, a, b, sha))

mid = MID_SRC.read_text()
sha_mid = hashlib.sha256(mid.encode()).hexdigest()
assert sha_mid[:12] == "febbc390ad4f", "MID MOVED (STOP)"
tail = TAIL_SRC.read_text()

# the l213_tail slice must carry the certs and STOP before the registered Qs
h213 = parts[-1]
for _need in ("CERT-207", "CERT-T", "o[\"premise\"]", "POP[_k] = dict("):
    assert _need in h213, ("l213_tail slice lost", _need)
for _bad in ("Q1_type", "Q2_class", "Q3_conditional", "json.dump(o",
             "mass strata", "def perm_within"):
    assert _bad not in h213, ("l213_tail slice OVERRAN into", _bad)
assert h213.rstrip().endswith('for k, v in POP.items()}'), \
    ("slice last line", h213.rstrip().splitlines()[-1])
assert "json.dump(a" in tail and "l213/addendum.json" in tail
assert 'open("l213/static.json"' not in tail, "TAIL opens the parent artifact"
assert "json.dump(o" not in tail, "TAIL would rewrite the parent dict"

banner = ('"""GENERATED by l213b_build.py — do not edit by hand.\n'
          + "".join(f"SLICE {p} [{a},{b}] sha256 {s[:16]}\n"
                    for p, a, b, s in shas)
          + f"MID l206_mid.py sha256 {sha_mid[:16]}\n"
          + f"TAIL l213b_tail.py sha256 "
            f"{hashlib.sha256(tail.encode()).hexdigest()[:16]}\n"
            'UNREGISTERED addendum. Writes l213/addendum.json ONLY.\n"""\n')

body = (banner + parts[0] + parts[1] + mid + parts[2] + parts[3] + parts[4]
        + parts[5] + tail)
OUT.write_text(body)
assert OUT.read_text() == body
for part in parts + [mid, tail]:
    assert part in body, "generated file lost a slice"
print(f"wrote {OUT} ({len(body.splitlines())} lines)")
for p, a, b, s in shas:
    print(f"SLICE {p} [{a},{b}] {s}")
print(f"GENERATED sha256 {hashlib.sha256(body.encode()).hexdigest()}")
