"""L202 verdict builder: helper block = l200/verdict_l200.py up to its tail
marker VERBATIM (the L198 helper block + duty14L_seeds) + the L202 tail."""
import hashlib
import py_compile
src = open("l200/verdict_l200.py").read()
assert hashlib.sha256(src.encode()).hexdigest() == \
    "480e6b577a7d17f2e37762dec5015b451eef8375e309212394695fefcfb9cd27"
MARK = "# ======================= L200 verdict tail (additive) =======================\n"
assert src.count(MARK) == 1
head = src[:src.index(MARK)]
head = head[head.index("\n") + 1:]           # skip the GENERATED banner line
assert "def wilson(k, n):" in head and "def duty_seeds(" in head and "def side_k(" in head
assert "def duty14_seeds(raw, a, seeds):" in head and "def duty14L_seeds(raw, a, seeds):" in head
assert head.rstrip().endswith("return np.array(L)")
out = ("# GENERATED by l202/build_verdict.py — helpers == l200/verdict_l200.py helper block VERBATIM\n"
       + head.rstrip("\n") + "\n" + open("l202/verdict_tail.py.txt").read())
open("l202/verdict_l202.py", "w").write(out)
py_compile.compile("l202/verdict_l202.py", doraise=True)
print("l202/verdict_l202.py written", len(out.splitlines()), "lines")
