"""L202 builder: count-asserted ADDITIVE transform of the certified L200
harness banc/l200/ru2_run.py -> banc/l202/nec_run.py. Run from banc/.
VERBATIM from l200/ru2_run.py: extraction, ladder, build()/wb()/pools_for(),
add_arm()/add_arm_multi()/add_alias()/add_base_alias()/gen_init(), the L187
arms block, the L198 twin block, the L200 ru2 block up to its static dump
(its selection re-pointed READ-ONLY at the frozen l200/selection.json),
settle_states, bisect_vec, the rollout step loop incl. the L200 carrier-replay
line, store keys, per-seed atomic checkpoints.
REPLACED: env names, seed list, output dir, the L200 static dump (-> L202
block: bilateral twins + edge arms + CERT-SUB + static pins), gains + anchors
block, tail.
ADDED: one ru2-replay line pair in each of the two rollout loops."""
import hashlib
import py_compile

SRC = "l200/ru2_run.py"
s = open(SRC).read()
SRC_SHA = hashlib.sha256(s.encode()).hexdigest()
assert SRC_SHA == "d3dffb6b70323692c86973b1ca785ecdbadda0daea7d22e500fd69ff6261f70b", SRC_SHA
assert s.count("\n") == 2329
NREP = 0


def rep(old, new, count=1):
    global s, NREP
    n = s.count(old)
    assert n == count, (old[:70], "found", n, "want", count)
    s = s.replace(old, new)
    NREP += n


def splice(opener, closer, new):
    global s, NREP
    assert s.count(opener) == 1, (opener[:60], s.count(opener))
    i = s.index(opener)
    if closer is None:
        j = len(s)
    else:
        assert s.count(closer) == 1, (closer[:60], s.count(closer))
        j = s.index(closer)
        assert j > i
    s = s[:i] + new + s[j:]
    NREP += 1


rep('"""L200 ru2_run.py — GENERATED by l200/build_ru2.py from l198/twin_run.py\n',
    '"""L202 nec_run.py — GENERATED by l202/build_nec.py from l200/ru2_run.py\n'
    '(sha256 ' + SRC_SHA + ').\n'
    'PREREG l202/PREREG.md FIRST. ru2-necessity replicate (sc25 / l2c, both gain\n'
    'forms), bilateral twins (lt4 / lt5), wipe specificity (t4c), ru2 replay clamp\n'
    'on the carrier-removed graph (s2k), chain batches (rcut / edge / sham), on\n'
    'the k=24 (cutwA) base. MODE env: static | work. cwd = banc/. L200 docstring\n'
    'retained below.\n\n'
    'L200 ru2_run.py — GENERATED by l200/build_ru2.py from l198/twin_run.py\n')
rep('torch.set_num_threads(int(os.environ.get("L200_THREADS", "1")))\n'
    'MODE = os.environ["L200_MODE"]\n'
    'assert MODE in ("static", "work"), MODE\n'
    'WID = int(os.environ.get("L200_WID", "0"))\n'
    'NW = int(os.environ.get("L200_NW", "6"))\n',
    'torch.set_num_threads(int(os.environ.get("L202_THREADS", "1")))\n'
    'MODE = os.environ["L202_MODE"]\n'
    'assert MODE in ("static", "work"), MODE\n'
    'WID = int(os.environ.get("L202_WID", "0"))\n'
    'NW = int(os.environ.get("L202_NW", "4"))\n')
rep('B44 = list(range(3705, 3721))       # FRESH (key-scanned absent, PREREG l200)\n'
    'SEEDS = ANCH_BIT + ANCH_175 + ANCH_187 + ANCH_198 + B44   # anchors FIRST\n'
    'FRESH = B44\n'
    'assert not (set(B44) & (set(B39) | set(B40) | set(B41) | set(B42) | set(B43)))\n'
    'assert ANCH_175[0] in B39 and ANCH_187[0] in B41 and ANCH_198[0] in B43\n',
    'B44 = list(range(3705, 3721))       # L200 batch: STORED, never re-sampled\n'
    'B45 = list(range(3737, 3753))       # FRESH (key-scanned absent, PREREG l202)\n'
    'SEEDS = ANCH_BIT + [3545, 3609, 3641, 3673, 3705] + B45   # anchors FIRST\n'
    'FRESH = B45\n'
    'assert not (set(B45) & (set(B39) | set(B40) | set(B41) | set(B42) | set(B43) | set(B44)))\n'
    'assert ANCH_175[0] in B39 and ANCH_187[0] in B41 and ANCH_198[0] in B43\n'
    'assert 3641 in B42 and 3705 in B44 and len(SEEDS) == 23\n')
rep('OUT = "l200"\n', 'OUT = "l202"\n')
rep('_fresh = set(B44)\n', '_fresh = set(B45)\n')
rep('    if _f.startswith("../banc/l200/"):\n        continue\n',
    '    if _f.startswith("../banc/l202/"):\n        continue\n')
rep('SEL200_PATH = f"{OUT}/selection.json"\n',
    'SEL200_PATH = "l200/selection.json"   # L202: the frozen L200 selection, READ-ONLY\n')
NEC_BLOCK = open("l202/nec_block.py.txt").read()
splice('if MODE == "static":\n    A4 = _a4()\n',
       '# ===================== end L175 GEN BLOCK =====================\n', NEC_BLOCK)
GAINS_BLOCK = open("l202/gains_block.py.txt").read()
splice('assert ANCH == [11, 22, 33]\n',
       '# ---------------- rollouts ----------------\n', GAINS_BLOCK)
TAIL_BLOCK = open("l202/tail_block.py.txt").read()
splice('log(f"rollouts done {time.time()-t0:.0f}s")\n', None, TAIL_BLOCK)
# ru2 replay clamp, rollout SETTLE loop (after the L200 carrier-replay line)
rep('            if a in CLAMPF:\n'
    '                X[a][CLAMPF[a], 0] = 0.0\n'
    '            if a in REPLAY:   # L200: carrier <- same-step cutwA carrier value\n'
    '                X[a][REPLAY[a], 0] = X["cutwA"][CARRIER_LOC, 0]\n',
    '            if a in CLAMPF:\n'
    '                X[a][CLAMPF[a], 0] = 0.0\n'
    '            if a in REPLAY:   # L200: carrier <- same-step cutwA carrier value\n'
    '                X[a][REPLAY[a], 0] = X["cutwA"][CARRIER_LOC, 0]\n'
    '            if a in REPLAY2:  # L202: ru2 <- same-step cutwA ru2 value\n'
    '                X[a][REPLAY2[a], 0] = X["cutwA"][RU2_LOC, 0]\n')
# ru2 replay clamp, rollout WINDOW loop
rep('            if a in CLAMP:\n'
    '                X[a][CLAMP[a], 0] = 0.0\n'
    '            if a in REPLAY:   # L200: carrier <- same-step cutwA carrier value\n'
    '                X[a][REPLAY[a], 0] = X["cutwA"][CARRIER_LOC, 0]\n',
    '            if a in CLAMP:\n'
    '                X[a][CLAMP[a], 0] = 0.0\n'
    '            if a in REPLAY:   # L200: carrier <- same-step cutwA carrier value\n'
    '                X[a][REPLAY[a], 0] = X["cutwA"][CARRIER_LOC, 0]\n'
    '            if a in REPLAY2:  # L202: ru2 <- same-step cutwA ru2 value\n'
    '                X[a][REPLAY2[a], 0] = X["cutwA"][RU2_LOC, 0]\n')
rep('    assert ARMS[0] == "cutwA" and all(a not in REPLAY or i > 0 for i, a in enumerate(ARMS))\n',
    '    assert ARMS[0] == "cutwA" and all((a not in REPLAY and a not in REPLAY2) or i > 0\n'
    '                                      for i, a in enumerate(ARMS))\n'
    '    assert not any(a in REPLAY for a in ARMS)   # L202 rolls no carrier-replay arm\n')

doc_end = s.index('"""', 3) + 3
code = s[doc_end:]
bad = []
for ln in code.split("\n"):
    if ln.strip().startswith("#"):
        continue
    c = ln.split("  #")[0]
    for tok in ('"L200_', 'OUT = "l200"', "_fresh = set(B44)", "FRESH = B44"):
        if tok in c:
            bad.append((tok, ln[:90]))
    if any(f"l{n}/" in c for n in (200, 198, 190, 187, 185, 175)):
        assert ("json.load(open(" in c) or ("np.load(" in c) or ("startswith" in c) \
            or ("pd.read_csv(" in c) or ('SEL_PATH = "l198/selection.json"' in c) \
            or ('SEL200_PATH = "l200/selection.json"' in c) \
            or ('assert SEL200_PATH == "l200/selection.json"' in c) \
            or ('"l175", ' in c or '"l187", ' in c or '"l190", ' in c or '"l198", ' in c
                or '"l200", ' in c), ("non-read", ln)
assert not bad, bad
# no write path may point outside l202: every atomic_json / atomic_savez target uses OUT
for ln in code.split("\n"):
    if "atomic_json(" in ln or "atomic_savez(" in ln:
        if ln.strip().startswith(("def ", "#")):
            continue
        assert ("{OUT}/" in ln) or ("_PATH" in ln) or ("SEL_PATH" in ln), ("write target", ln)
assert s.count('OUT = "l202"\n') == 1
for keep in (
        "            drive = torch.sparse.mm(WB[a], X[a]) * GAIN[a] + Iv[a]\n"
        "            if sin_t > 0:\n"
        "                drive[mech[a], 0] = drive[mech[a], 0] + sin_t\n"
        "            t = torch.relu(drive + BG)\n"
        "            t = (t + noise[a]).clamp(max=RMAX)\n"
        "            X[a] = X[a] + (DT / TAU) * (t - X[a])\n"
        "            if a in CLAMP:\n"
        "                X[a][CLAMP[a], 0] = 0.0\n",
        "    atomic_savez(RAW_PATH, store)\n    atomic_savez(XM_PATH, XM)\n"
        "    post_seed(seed)\n"):
    assert s.count(keep) == 1, keep[:50]
assert s.count('X[a][REPLAY[a], 0] = X["cutwA"][CARRIER_LOC, 0]\n') == 2
assert s.count('X[a][REPLAY2[a], 0] = X["cutwA"][RU2_LOC, 0]\n') == 2
for need in ("def add_arm(", "def gen_init(", "def bisect_vec(", "def post_seed(",
             "def arms_for(", "def settle_states(", "def select_twin(", "def select_left(",
             "def _a4(", "def _replay_cert(", "def add_edge_arm("):
    assert s.count(need) == 1, need
open("l202/nec_run.py", "w").write(s)
py_compile.compile("l202/nec_run.py", doraise=True)
print(f"l202/nec_run.py written: {s.count(chr(10))} lines, {NREP} rep sites, src sha {SRC_SHA[:12]}")
